import copy
nested = [[1, 2], [3, 4]]
deep = copy.deepcopy(nested)


# ============================================================
# 九、遍历技巧
# ============================================================
fruits = ["苹果", "香蕉", "橘子"]

# 方法 1：直接遍历元素
for f in fruits:
    print(f)

# 方法 2：enumerate 同时取索引和值
for i, f in enumerate(fruits):
    print(f"第{i+1}个: {f}")

# 方法 3：只遍历索引
for i in range(len(fruits)):
    print(fruits[i])

# 方法 4：zip 并行遍历两个列表
names = ["张三", "李四", "王五"]
scores = [95, 87, 92]
for name, score in zip(names, scores):
    print(f"{name}: {score}分")


# ============================================================
# 十、列表推导式（重点）
# ============================================================
# 基本格式：[表达式 for 变量 in 可迭代对象 if 条件]

# 基础
[x**2 for x in range(5)]               # [0, 1, 4, 9, 16]

# 加条件
[x for x in range(20) if x % 3 == 0]   # [0, 3, 6, 9, 12, 15, 18]

# 嵌套
[(x, y) for x in range(3) for y in range(3)]
# [(0,0), (0,1), (0,2), (1,0), (1,1), (1,2), (2,0), (2,1), (2,2)]

# 条件表达式（三元）
["大" if x > 5 else "小" for x in [3, 7, 2, 9]]
# ["小", "大", "小", "大"]

# 字符串处理
words = "hello world python"
[w.upper() for w in words.split()]     # ["HELLO", "WORLD", "PYTHON"]


# ============================================================
# 十一、嵌套列表（二维列表 / 矩阵）
# ============================================================
matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]

# 访问元素
matrix[0]        # [1, 2, 3]
matrix[0][1]     # 2
matrix[2][2]     # 9

# 遍历
for row in matrix:
    for item in row:
        print(item, end=" ")   # 1 2 3 4 5 6 7 8 9

# 取出某一列
col2 = [row[1] for row in matrix]    # [2, 5, 8]

# 转置（行变列）
transposed = list(zip(*matrix))
# [(1, 4, 7), (2, 5, 8), (3, 6, 9)]


