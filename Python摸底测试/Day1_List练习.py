# 练习 8 · 成绩分组（10 分）
# 给定一个分数列表，请将分数分为两组：
#   及格组（>= 60）和不及格组（< 60），每组内部按从高到低排序。
# ============================================================
exam_scores = [45, 78, 92, 55, 88, 60, 73, 49, 81, 66]
passed = []    # >= 60，从高到低
failed = []    # < 60，从高到低
# 请在此处编写代码

for score in exam_scores:
    if score >= 60:
        passed.append(score)
    else:
        failed.append(score)

passed.sort(reverse=True)
failed.sort(reverse=True)

print("及格名单：", passed)
print("不及格名单：", failed)
