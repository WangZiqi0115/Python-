# 练习 7 · 实战：坐标距离计算（10 分）
# 题目：实现一个函数 distance(p1, p2)
# p1 和 p2 是两个元组 (x, y)，计算两点之间的直线距离
# 公式：√[(x1-x2)² + (y1-y2)²]
# 提示：用 **0.5 或 math.sqrt 开平方
# ============================================================
import math

def distance(p1, p2):
    """
    示例：
    distance((0, 0), (3, 4)) -> 5.0
    distance((1, 1), (4, 5)) -> 5.0
    """
    # 请在此处编写代码
    x1,y1 = p1
    x2,y2 = p2
    return round(((x1 - x2) ** 2 + (y1 - y2) ** 2) ** 0.5,2)

