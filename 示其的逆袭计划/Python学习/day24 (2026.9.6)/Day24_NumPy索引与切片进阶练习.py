# ============================================================
# 练习 7 · 视图 vs 拷贝 · 区分联动(10 分)
# 下面这段把一个子块改掉,观察原数组发生了什么
# ============================================================
m = np.arange(12).reshape(3, 4)
sub = m[0:2, 0:2]
sub[0, 0] = 999
print("改过 sub 后,原 m =", m)        # 观察:原数组变了吗?哪一位变了?
# 请在下方写代码:
#   (1) 用一句注释回答:为什么原 m 会被改掉?这叫什么?(提示:视图/拷贝)
#在视图的基础上改变会影响原数组
#   (2) 再用 .copy() 重新做一遍,让原 m 不被影响
#   (3) print 出来,确认这次原 m 没变
sub = m[0:2, 0:2].copy()
sub[0, 0] = 999
print("改过 sub 后,原 m =", m)

