# ============================================================
# 练习 2 · 步长切片 · 翻转(10 分)
# 对下面这个 3x3 数组,分别打印"上下翻转"和"左右翻转"的结果
# ============================================================
grid = np.arange(9).reshape(3, 3)
# 上下翻转: 用 [::-1] 这种负数步长
# 左右翻转: 用 [:, ::-1]
# 请在下方写代码(各一行 print)
# 期望: 上下翻转后第0行变成 [6 7 8];左右翻转后第0行变成 [2 1 0]
