import numpy as np

# ============================================================
# 练习 1 · 步长切片 · 隔行隔列取(10 分)
# 下面这个 5x5 数组,用步长切片取出"行、列都隔一个"的 3x3 子块
# ============================================================
arr25 = np.arange(25).reshape(5, 5)
# 请在下方写代码(用 [::2, ::2] 这种步长写法,print 出来)
# 期望输出是这个 3x3 的棋盘格:
# [[ 0  2  4]
#  [10 12 14]
