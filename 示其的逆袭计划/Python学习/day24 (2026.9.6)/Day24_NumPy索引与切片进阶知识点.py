# 七、例题精讲(先看懂例题,再去做练习)
# ============================================================

# ------------------------------------------------------------
# 例题 1:步长切片 → 把一张图"隔像素"缩小(降采样)
# 思路:img[::2, ::2] 行、列都隔一个取,28x28 → 14x14
# ------------------------------------------------------------
img = np.random.rand(28, 28)
print("\n例题1 原图形状:", img.shape)
down = img[::2, ::2]
print("隔像素取样后形状:", down.shape)      # (14, 14)
print("保留的像素数:", down.size, "→ 只有原来的", down.size / img.size, "倍")
# 关键点:步长 2 就让像素数变成 1/4。步长越大图越小,计算量越省,但会丢细节。

# ------------------------------------------------------------
# 例题 2:布尔掩码做二值化(把灰度图变黑白)
# 思路:img >= 128 得掩码,再用 np.where 把亮处填255、暗处填0
# ------------------------------------------------------------
img2 = np.array([[60, 180], [250, 30]])
mask = img2 >= 128                    # [[False  True  True False]]
binary = np.where(mask, 255, 0)
print("\n例题2 原灰度图:\n", img2)
print("二值化后:\n", binary)
# [[  0 255]
#  [255   0]]
# 关键点:阈值 128 是"分界线";两边被强行拉成纯黑/纯白,去掉了中间过渡。

# ------------------------------------------------------------
# 例题 3:花式索引洗牌打乱一批样本
# 思路:先有一个顺序名单 indices,再用 arr[indices] 按名单重新排
# ------------------------------------------------------------
samples = np.array([100, 200, 300, 400, 500])     # 5个样本
print("\n例题3 原始样本:\n", samples)
indices = np.array([3, 1, 4, 0, 2])               # 一份"打乱后的顺序"
print("洗牌后:\n", samples[indices])
# [400 200 500 100 300]
# 关键点:每次训练前重新随机生成 indices,再用它取,数据就"洗"开了。

# ------------------------------------------------------------
# 例题 4:视图联动 + copy 保护(最容易踩的坑)
# 思路:先演示基本切片会联动,再用 .copy() 隔离
# ------------------------------------------------------------
m7 = np.arange(16).reshape(4, 4)
view = m7[0:2, 0:2]       # 视图
view[0, 0] = -1           # 改视图
print("\n例题4 切了子块并改它,原 m7:\n", m7)    # (0,0) 变成 -1 了
safe = m7[0:2, 0:2].copy()
safe[0, 0] = -2
print("用 copy 再改,原 m7 仍为:\n", m7)          # 第一个元素还是 -1,没变 -2
# 关键点:要"改一份但不动原件",就 .copy();想"节省内存、共享改动"就留视图。


# ============================================================
# 八、常见陷阱
# ============================================================
# 陷阱 1:忘了切片是"左闭右开" → 差一位
#   m[0:2] 取的是索引 0、1(不含 2),想取到第 3 行要写 m[0:3]。
#
# 陷阱 2:改基本切片的"视图"会连带改原数组
#   sub = m[..., ...]; sub[0,0]=99 → 原数组也变。不想联动就 .copy()。
#
# 陷阱 3:不确定布尔索引和花式索引是拷贝,以为改了会联动
#   恰恰相反:布尔/花式索引返回的是**新数组**,改它不影响原数组。
#   所以"想改原数组的某些元素"要用"掩码赋值":  m[m>4] = 0  (直接写回 m)。
#
# 陷阱 4:步长为 0 会报错
#   m[::0] → ValueError: slice step cannot be zero
#
# 陷阱 5:索引越界用普通下标 → 报错;用切片 → 自动截断不报错
#   m[5, 0]  → IndexError
#   m[0:99]  → 不报错,取到边界为止。
#
# 陷阱 6:想在切片里同时用"多个条件的与/或",别用 and/or,要用位运算
#   (a > 4) and (a < 8)   → 不能用! 要用 (a > 4) & (a < 8)
#   【怎么读】两个 & 是"按位与",对掩码来说就是"同时满足"。| 是"或"。
print("\n--- 陷阱6 演示 ---")
a2 = np.array([1, 5, 3, 8])
print("介于4和8之间:", a2[(a2 > 4) & (a2 < 8)])    # [5]
# 注意:条件各自要加括号,(a2>4) & (a2<8),顺序别乱。


