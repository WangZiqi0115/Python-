# ============================================================
# 一、元组是什么
# ============================================================
# 元组和列表一样，都是存放多个元素的"容器"
# 区别：列表用 []，元组用 ()
# 区别：列表可以修改，元组创建后不能修改

# 创建元组
t1 = (1, 2, 3)
t2 = ()                     # 空元组
t3 = (5,)                   # 只有一个元素的元组，逗号不能省！
t4 = 1, 2, 3                # 可以省略括号，自动识别为元组

# 错误示范：
# not_tuple = (5)           # 这不是元组，是整数 5！
# print(type(not_tuple))    # <class "int">

# 用 tuple() 转换
t5 = tuple([1, 2, 3])       # (1, 2, 3)  列表转元组
t6 = tuple("hello")         # ("h", "e", "l", "l", "o")  字符串转元组


# ============================================================
# 二、元组的操作（和列表很像！）
# ============================================================
t = (10, 20, 30, 40, 50)

# 访问元素 — 和列表一样
t[0]            # 10
t[-1]           # 50
t[1:3]          # (20, 30)  切片结果还是元组

# 查找统计 — 和列表一样
t.index(30)     # 2
t.count(20)     # 1
len(t)          # 5
20 in t         # True

# 遍历 — 和列表一样
for x in t:
    print(x)

for i, v in enumerate(t):
    print(i, v)

# 合并与重复
t1 = (1, 2)
t2 = (3, 4)
t1 + t2          # (1, 2, 3, 4)
t1 * 3           # (1, 2, 1, 2, 1, 2)


# ============================================================
# 三、元组不能做什么（和列表的关键区别）
# ============================================================
t = (1, 2, 3)

# 以下操作都会报错，因为元组不可变：
# t[0] = 99        ❌ TypeError
# t.append(4)      ❌ AttributeError
# t.remove(2)      ❌ AttributeError
# t.pop()          ❌ AttributeError
# t.sort()         ❌ AttributeError
# t.clear()        ❌ AttributeError

# 元组只有两个方法：count 和 index，因为其他方法都涉及修改


# ============================================================
# 四、核心概念：可变 vs 不可变（非常重要）
# ============================================================
# 可变（Mutable）：创建后可以修改内容 → 列表、字典、集合
# 不可变（Immutable）：创建后不能修改内容 → 整数、浮点数、字符串、元组、布尔值

# 理解"不能修改"到底是什么意思：

# ✅ 列表可变 — 可以改内容
a = [1, 2, 3]
a[0] = 99          # ✅ 可以改
a.append(4)        # ✅ 可以加
print(a)           # [99, 2, 3, 4]

# ❌ 元组不可变 — 不能改内容
b = (1, 2, 3)
# b[0] = 99        ❌ 报错

# ❌ 字符串也不可变
c = "hello"
# c[0] = "H"       ❌ 报错

# ✅ 但可以重新赋值（注意：重新赋值不是修改，是让变量指向新的地址）
c = "Hello"        # ✅ 这是创建了一个新字符串，让 c 指向它


# ============================================================
# 五、为什么学元组？—— 它和引用模型的关系
# ============================================================
# 还记得昨天学的 b = a 是别名吗？
# 为什么 b = a 改 b 会让 a 也跟着变？
# 因为列表是可变对象，b 和 a 指向同一个地址，改内容就是改那个地址里的东西

# 但如果 b 指向的是不可变对象呢？

x = 5
y = x
y = 10
print(x)           # 5（没变！）

# 为什么这里 x 没变？
# 因为整数不可变，y = 10 不是把 5 改成 10
# 而是让 y 指向一个新的地址（存着 10），x 还指向原来的地址（存着 5）

# 元组也是一样：
t1 = (1, 2, 3)
t2 = t1
# t2[0] = 99       ❌ 报错！元组根本不能改
t2 = (4, 5, 6)     # ✅ 可以，这是让 t2 指向新元组
print(t1)          # (1, 2, 3)  t1 不受影响


# ============================================================
# 六、元组解包（重点）
# ============================================================
# 解包：把元组的元素拆开，分别赋值给多个变量

# 基础解包
point = (3, 5)
x, y = point          # x = 3, y = 5
print(x, y)           # 3 5

# 交换两个变量（Python 经典用法）
a, b = 1, 2
a, b = b, a           # 一行交换！本质就是元组解包
print(a, b)           # 2 1

# 函数返回多个值（本质就是返回元组）
def get_min_max(nums):
    return min(nums), max(nums)   # 返回一个元组

result = get_min_max([3, 7, 2, 9, 5])
print(result)          # (2, 9)

mn, mx = get_min_max([3, 7, 2, 9, 5])
print(mn, mx)          # 2 9

# enumerate 和 zip 返回的就是元组
for item in enumerate(["a", "b", "c"]):
    print(item)        # (0, "a")  (1, "b")  (2, "c")

for i, v in enumerate(["a", "b", "c"]):
    print(i, v)        # 0 a    1 b    2 c   ← 这就是解包！


# ============================================================
# 七、什么时候用元组 vs 列表？
# ============================================================
# 元组：数据固定不变的时候用
# 列表：数据会变化的时候用

# ✅ 适合元组的场景：
# 坐标点 (x, y)
# 函数返回多个值
# 字典的 key（只有元组能做 key，列表不行！）
# 不需要修改的数据集合

# ✅ 适合列表的场景：
# 待办事项（要增删改）
# 购物车（要增删）
# 需要排序的数据


# ============================================================
# 八、补充：可变对象作为函数参数的陷阱
# ============================================================
# 这个坑面试常考，先有个印象就行

def add_item(item, lst=[]):
    lst.append(item)
    return lst

print(add_item(1))       # [1]
print(add_item(2))       # [2]? 不对，是 [1, 2]！
# 因为默认参数 lst=[] 只创建一次，多次调用用的是同一个列表

# 正确的写法：
def add_item_safe(item, lst=None):
    if lst is None:
        lst = []
    lst.append(item)
    return lst

print(add_item_safe(1))  # [1]
print(add_item_safe(2))  # [2]  ✅ 每次都是新的


