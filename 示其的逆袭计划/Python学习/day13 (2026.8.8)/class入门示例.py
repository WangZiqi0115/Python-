# 3. 类型注解（只是提示，不影响运行）
# ============================================================
from typing import List

class Solution2:
    def twoSum(self, nums: List[int], target: int) -> List[int]:
        # nums: List[int] = 参数类型注解（提示：整数列表）
        # target: int = 参数类型注解（提示：整数）
        # -> List[int] = 返回值类型注解（提示：返回整数列表）
        # 行尾冒号 = 函数体开始（和普通 def 一样）
        # 简单实现：找两个数相加等于 target
        for i in range(len(nums)):
            for j in range(i + 1, len(nums)):
                if nums[i] + nums[j] == target:
                    return [i, j]
        return []

s = Solution2()
print("twoSum([2,7,11,15], 9)：", s.twoSum([2, 7, 11, 15], 9))   # [0, 1]


