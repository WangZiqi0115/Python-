# ============================================================
# 2. 类 + self（LeetCode 的写法）
# ============================================================
class Solution:
    # class 不是必须的，作用是"把相关数据和方法打包"、一个模板造多个对象
    # LeetCode 用 class 是为了统一测试接口：平台创建对象后调用方法
    def add(self, a, b):
        # self = 当前对象自己（调用时自动传入，不用手动写）
        # 用处：方法内部访问对象的数据/其他方法（如 self.xxx）
        # 约定：第一个参数固定叫 self，名字可改但大家都不改
        return a + b

solution = Solution()          # 创建对象（固定步骤）
print("类方法：", solution.add(3, 5))    # 8
# 调用时 self 自动传入，不需要写 solution.add(solution, 3, 5)


