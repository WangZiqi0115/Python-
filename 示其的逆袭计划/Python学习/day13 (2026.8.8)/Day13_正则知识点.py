# ============================================================
# 一、为什么要学正则
# ============================================================
# 你之前找东西都是"精确查找"：
#   "hello world".find("world")    只能找固定内容
#   startswith / endswith / in    只能做简单判断
#
# 正则能"模糊查找"：
#   找所有电话号码、所有邮箱、所有数字、所有网址
#   校验输入格式（手机号、身份证、邮箱）
#   爬虫提取网页数据、日志分析提取 IP
#
# 适用场景：
#   数据处理、爬虫、表单校验、日志分析、文本提取


# ============================================================
# 二、导入 re 模块
# ============================================================
# 正则功能在 re 模块里（Python 标准库，不用安装）
import re

# 字符串前面加 r 表示"原始字符串"：
#   r"\d+" 里的 \d 不会被 Python 转义成别的意思
#   写正则统一用 r"..." 最安全


# ============================================================
# 三、三个最常用函数
# ============================================================
import re

# 1. re.findall(模式, 文本) → 找到所有匹配，返回列表
re.findall(r"\d+", "我有3个苹果和12个橘子")
# ['3', '12']

# 2. re.search(模式, 文本) → 找到第一个匹配，返回对象或 None
m = re.search(r"\d+", "电话13812345678")
m.group()            # '13812345678'  用 .group() 取出匹配内容
# m.group(0) 等价 m.group()

# 3. re.fullmatch(模式, 文本) → 整个字符串完全匹配才返回对象
re.fullmatch(r"1\d{10}", "13812345678")    # 匹配对象
re.fullmatch(r"1\d{10}", "abc13812345678") # None（开头有多余字符）
# 最常用于"校验输入格式"


# ============================================================
# 四、基础符号速查
# ============================================================
import re

# 字符类（匹配某一种字符）
r"\d"        # 一个数字（0-9）
r"\w"        # 一个单词字符（字母/数字/下划线）
r"\s"        # 一个空白（空格/换行/制表）
r"."         # 任意一个字符（换行除外）
r"[abc]"     # a、b、c 中的任意一个
r"[0-9]"     # 等价 \d
r"[a-z]"     # 任意小写字母
r"[^0-9]"    # 不是数字的任意字符

# 数量（控制前一个出现多少次）
r"\d*"       # 数字出现 0 次或多次（可以没有）
r"\d+"       # 数字出现 1 次或多次（至少1个）
r"\d?"       # 数字出现 0 次或 1 次（可选）
r"\d{3}"     # 数字恰好 3 次
r"\d{3,5}"   # 数字 3~5 次
r"\d{3,}"    # 数字至少 3 次

# 位置（锚点）
r"^hello"    # 以 hello 开头
r"world$"    # 以 world 结尾

# 常见组合：
r"\d+"       # 一串数字
r"\w+"       # 一个单词
r"\d{11}"    # 恰好 11 位数字（手机号）
r"\d{4}-\d{2}-\d{2}"   # 日期 2026-08-08


# ============================================================
# 五、raw 字符串 r"" 是什么意思
# ============================================================
# 普通字符串里 \n 是换行、\t 是制表符
# r"..." 里 \n 就是反斜杠+n 两个字符，不做转义
# 正则里正好需要反斜杠，所以统一用 r"..."

print("a\nb")    # a 换行 b
print(r"a\nb")   # a\nb（原样显示）

# 不加 r 也能写正则，但要写成 "\\d"（两个反斜杠）
# 太麻烦，所以约定：正则永远用 r"..." 


# ============================================================
# 六、分组 ( )
# ============================================================
# 用括号把正则分成几组，方便分别提取
import re

text = "张三 13800138000 重庆"
m = re.search(r"(\w+) (\d{11}) (\w+)", text)
m.group(1)     # '张三'
m.group(2)     # '13800138000'
m.group(3)     # '重庆'

# findall 里有分组时，返回的是元组列表：
re.findall(r"(\w+) (\d{11})", "张三 13800138000 李四 13900139000")
# [('张三', '13800138000'), ('李四', '13900139000')]


# ============================================================
# 七、实战应用
# ============================================================
import re

# 场景 1：提取所有数字
nums = re.findall(r"\d+", "成绩：95分，排名：3，比例：87.5%")
# ['95', '3', '87', '5']

# 场景 2：提取所有单词
words = re.findall(r"\w+", "Hello, world! Python is fun.")
# ['Hello', 'world', 'Python', 'is', 'fun']

# 场景 3：手机号校验
def is_valid_phone(phone):
    return re.fullmatch(r"1\d{10}", phone) is not None

is_valid_phone("13812345678")   # True
is_valid_phone("23812345678")   # False（不是1开头）

# 场景 4：邮箱简单校验
def is_valid_email(email):
    return re.fullmatch(r"\w+@\w+\.\w+", email) is not None

is_valid_email("abc@qq.com")    # True
is_valid_email("abc@qq")        # False（缺 .com）

# 场景 5：从日志提取 IP
log = "192.168.1.1 - - [08/Aug/2026] GET /index.html"
ip = re.search(r"\d+\.\d+\.\d+\.\d+", log).group()
# '192.168.1.1'


# ============================================================
# 八、常见陷阱
# ============================================================

# 陷阱 1：忘记加 r → 反斜杠被转义
# re.findall("\d+", text)  # 可能报错或结果不对，应写 r"\d+"

# 陷阱 2：* 和 + 的区别
# * 可以匹配 0 次（没有也匹配），+ 至少要 1 次
# re.findall(r"\d*", "abc")  → ['', '', '', '']  空也算！
# re.findall(r"\d+", "abc")  → []  没有就不匹配

# 陷阱 3：fullmatch vs search
# fullmatch：整个字符串必须完全符合模式
# search：只要某一部分符合就算匹配
# 校验格式用 fullmatch，找内容用 search/findall

# 陷阱 4：中文匹配
# \w 匹配不了中文，中文用 [\u4e00-\u9fa5] 或 r"[一-龥]"
# re.findall(r"[\u4e00-\u9fa5]+", "我是shichi")  → ['我是']
