# 正则功能在 re 模块里（Python 标准库，不用安装）
import re

# 字符串前面加 r 表示"原始字符串"：
#   r"\d+" 里的 \d 不会被 Python 转义成别的意思
#   写正则统一用 r"..." 最安全


# ============================================================
# 三、三个最常用函数
# ============================================================
import re

# 1. re.findall(模式, 文本) → 找到所有匹配，返回列表
re.findall(r"\d+", "我有3个苹果和12个橘子")
# ['3', '12']

# 2. re.search(模式, 文本) → 找到第一个匹配，返回对象或 None
m = re.search(r"\d+", "电话13812345678")
m.group()            # '13812345678'  用 .group() 取出匹配内容
# m.group(0) 等价 m.group()
#
# 【补充】m 是什么？m 是"匹配对象"（re.Match），不是字符串
#   匹配对象里装：匹配文本（.group()）、起止位置（.start()/.end()）、分组
#   没匹配到时 re.search 返回 None，调用 .group() 前先 if m: 判断

# 3. re.fullmatch(模式, 文本) → 整个字符串完全匹配才返回对象
re.fullmatch(r"1\d{10}", "13812345678")    # 匹配对象
re.fullmatch(r"1\d{10}", "abc13812345678") # None（开头有多余字符）
# 最常用于"校验输入格式"
#
# 【补充】是不是只有 search 需要 .group()？
#   findall：直接返回内容列表，不需要 .group()
#   search / fullmatch：都返回 Match 对象，取内容都要 .group()
#   fullmatch 常被用于校验（只判断 is not None），所以看着像不用取

# 【补充】findall 返回列表，search 返回字符串吗？
#   不完全是：findall 直接返回列表；search 返回 Match 对象，不是字符串
#   想要字符串必须 .group()：re.search(...).group()
#
# 【补充】三个函数怎么区分？
#   findall  = "有哪些"：找出所有匹配，返回列表 → 提取数据用
#   search   = "有没有/第一个"：返回第一个匹配对象或 None → 查存在用
#   fullmatch = "整个字符串是不是完全符合"：返回对象或 None → 校验格式用
#   记忆：全都要→findall；搜第一个→search；严查到底→fullmatch


# ============================================================
# 四、基础符号速查
# ============================================================
import re

# 字符类（匹配某一种字符）
r"\d"        # 一个数字（0-9）
r"\w"        # 一个单词字符（字母/数字/下划线）
r"\s"        # 一个空白（空格/换行/制表）
r"."         # 任意一个字符（换行除外）
r"[abc]"     # a、b、c 中的任意一个
r"[0-9]"     # 等价 \d
r"[a-z]"     # 任意小写字母
r"[^0-9]"    # 不是数字的任意字符

# 数量（控制前一个出现多少次）
r"\d*"       # 数字出现 0 次或多次（可以没有）
r"\d+"       # 数字出现 1 次或多次（至少1个）
r"\d?"       # 数字出现 0 次或 1 次（可选）
r"\d{3}"     # 数字恰好 3 次
r"\d{3,5}"   # 数字 3~5 次
r"\d{3,}"    # 数字至少 3 次

# 位置（锚点）
r"^hello"    # 以 hello 开头
r"world$"    # 以 world 结尾

# 常见组合：
r"\d+"       # 一串数字
r"\w+"       # 一个单词
r"\d{11}"    # 恰好 11 位数字（手机号）
r"\d{4}-\d{2}-\d{2}"   # 日期 2026-08-08
#
# 【补充】正则里普通字符（不带 \ 的）匹配它自己：
#   r"1\d{10}" = 字符"1" + 10位数字（手机号）
#   r"cat" = 连续的 c-a-t
#   r"2026" = 数字串2026（普通数字也是匹配自己）
#   只有带 \ 的（\d \w \s）或特殊符号（+ * ? ()）才是特殊含义


# ============================================================
# 五、raw 字符串 r"" 是什么意思
# ============================================================
# 普通字符串里 \n 是换行、\t 是制表符
# r"..." 里 \n 就是反斜杠+n 两个字符，不做转义
# 正则里正好需要反斜杠，所以统一用 r"..."

print("a\nb")    # a 换行 b
print(r"a\nb")   # a\nb（原样显示）

# 不加 r 也能写正则，但要写成 "\\d"（两个反斜杠）
# 太麻烦，所以约定：正则永远用 r"..." 


# ============================================================
# 六、分组 ( )
# ============================================================
# 用括号把正则分成几组，方便分别提取
import re

text = "张三 13800138000 重庆"
m = re.search(r"(\w+) (\d{11}) (\w+)", text)
m.group(1)     # '张三'
m.group(2)     # '13800138000'
m.group(3)     # '重庆'

# findall 里有分组时，返回的是元组列表：
re.findall(r"(\w+) (\d{11})", "张三 13800138000 李四 13900139000")
# [('张三', '13800138000'), ('李四', '13900139000')]
#
# 【补充】findall 怎么分开多个人？
#   它从头到尾连续扫描：找到一个"匹配单元"就记录，然后从结束位置继续找
#   模式 r"(\w+) (\d{11})" 本身规定了边界（单词+空格+11位数字）
#   有括号时返回元组列表，每个元组 = 一个匹配的分组内容


# ============================================================
# 七、实战应用
# ============================================================
import re

# 场景 1：提取所有数字
nums = re.findall(r"\d+", "成绩：95分，排名：3，比例：87.5%")
# ['95', '3', '87', '5']

# 场景 2：提取所有单词
words = re.findall(r"\w+", "Hello, world! Python is fun.")
# ['Hello', 'world', 'Python', 'is', 'fun']

# 场景 3：手机号校验
def is_valid_phone(phone):
    return re.fullmatch(r"1\d{10}", phone) is not None
# 【补充】这一行的意思：
#   re.fullmatch(模式, phone) 匹配成功返回对象、失败返回 None
#   is not None 判断"不是 None"→ 成功 True / 失败 False
#   整体就是把"匹配结果"翻译成布尔值交给调用者

is_valid_phone("13812345678")   # True
is_valid_phone("23812345678")   # False（不是1开头）

# 场景 4：邮箱简单校验
def is_valid_email(email):
    return re.fullmatch(r"\w+@\w+\.\w+", email) is not None
# 【补充】邮箱正则里的 \. 是什么？
#   . 在正则是特殊符号（匹配任意字符），所以"真的点号"要转义成 \.
#   不加 \：abc.com 会匹配 abcXcom（任意字符也行）→ 校验不严谨
#   需要转义的特殊符号：. + * ? ( ) [ ] { } ^ $ | \
#   记忆：没被 \ 保护的 . 是"任意字符"，\. 才是字面点号

is_valid_email("abc@qq.com")    # True
is_valid_email("abc@qq")        # False（缺 .com）

# 场景 5：从日志提取 IP
log = "192.168.1.1 - - [08/Aug/2026] GET /index.html"
ip = re.search(r"\d+\.\d+\.\d+\.\d+", log).group()
# '192.168.1.1'


# ============================================================
# 八、常见陷阱
# ============================================================

# 陷阱 1：忘记加 r → 反斜杠被转义
# re.findall("\d+", text)  # 可能报错或结果不对，应写 r"\d+"

# 陷阱 2：* 和 + 的区别
# * 可以匹配 0 次（没有也匹配），+ 至少要 1 次
# re.findall(r"\d*", "abc")  → ['', '', '', '']  空也算！
# re.findall(r"\d+", "abc")  → []  没有就不匹配

# 陷阱 3：fullmatch vs search
# fullmatch：整个字符串必须完全符合模式
# search：只要某一部分符合就算匹配
# 校验格式用 fullmatch，找内容用 search/findall

# 陷阱 4：中文匹配
# \w 匹配不了中文，中文用 [\u4e00-\u9fa5] 或 r"[一-龥]"
# re.findall(r"[\u4e00-\u9fa5]+", "我是shichi")  → ['我是']
