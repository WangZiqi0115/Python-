# ------------------------------------------------------------
# 例题 1:广播 —— 全班成绩,每科加"平时分"
# 思路:(3,3) 加 (3,):从右往左,3=3 对得上 → 每行都加同一个平时分向量
# ------------------------------------------------------------
print("\n--- 例题1: 广播加平时分 ---")
scores = np.array([[80., 70., 60.],   # 学生0: 语数英
                   [90., 75., 65.],   # 学生1
                   [85., 80., 70.]])  # 学生2
bonus = np.array([5., 3., 2.])        # 语文+5、数学+3、英语+2(每科一个分)
print("scores:\n", scores)
print("bonus(3,) 每科平时分:", bonus)
total_s = scores + bonus
print("scores + bonus:\n", total_s)
# [[85. 73. 62.]
#  [95. 78. 67.]
#  [90. 83. 72.]]
print("形状:", total_s.shape)         # (3, 3) 形状没变,只是每个数都加了对应科的平时分
# 手算: 学生0 = [80+5, 70+3, 60+2] = [85, 73, 62] ✓
# 关键点: 想给"每行(每个样本)都加同一个向量",形状写成 (列数,) 就能广播;
#        想给"每列"加不同东西,记得先想清楚对齐的是哪一端(右端!)。

# ------------------------------------------------------------
# 例题 2:聚合 —— 找出总分最高的学生
# 思路:先 sum(axis=1) 得每人总分 → 再 argmax 找最大总分的下标
# ------------------------------------------------------------
print("\n--- 例题2: 谁总分最高 ---")
sc = np.array([[70., 80., 90.],   # 学生0
               [88., 76., 60.],   # 学生1
               [55., 99., 80.],   # 学生2
               [95., 85., 75.]])  # 学生3
print("sc(4个学生 × 3科):\n", sc)
total = np.sum(sc, axis=1)        # axis=1 → 每行(每个学生)的总分
print("每人总分:", total)          # [240. 224. 234. 255.]
print("总分最高的是下标:", np.argmax(total))   # 3(下标3 = 第4个学生)
# 手算: 学生3 = 95+85+75 = 255 最大 ✓
# 关键点: argmax 只回答"在第几个位置",下标从 0 数;MNIST 里猜"是几"就是 argmax。

# ------------------------------------------------------------
# 例题 3:随机 —— 洗牌并验证可复现
# 思路:permutation 返回乱序下标,用 labels[下标] 重排;固定 seed 就能复现
# ------------------------------------------------------------
print("\n--- 例题3: 洗牌与复现 ---")
np.random.seed(7)
labels = np.array([0, 1, 2, 3, 4])     # 5 张图各自的标签(答案)
order = np.random.permutation(5)       # 乱序下标
print("seed(7)后 permutation(5):", order)          # [0 3 2 1 4]
print("labels[order]:", labels[order])             # [0 3 2 1 4]  ← 标签跟着图一起乱序
np.random.seed(7)                                  # 同一存档点
order2 = np.random.permutation(5)
print("再 seed(7)+permutation(5):", labels[order2])  # [0 3 2 1 4] 一模一样 → 可复现
# 关键点: 训练时图和标签要"用同一个 order"一起重排,不然图和答案就对不上号了;
#        seed 必须设在 shuffle 之前,且想复现就要在每次实验开头设同一次。

# ------------------------------------------------------------
# 例题 4:广播 + 聚合 + keepdims —— 每张图"减掉自己的平均亮度"
# 思路:mean(axis=1, keepdims=True) 得每行均值 (4,1) → X - 它 → 每行中心化
# ------------------------------------------------------------
print("\n--- 例题4: 每行减自己的均值 ---")
X2 = np.array([[1., 2., 3.],       # 4 张"图",每张 3 个像素(简化)
               [4., 5., 6.],
               [7., 8., 9.],
               [10., 11., 12.]])
print("X2(4张'图',每张3像素):\n", X2)
mean_row = X2.mean(axis=1, keepdims=True)    # (4,1):每行一个均值,还留着"行"这个壳
print("mean_row(4,1):\n", mean_row)          # [[2.],[5.],[8.],[11.]]
centered = X2 - mean_row                     # 广播:第 i 行 - 第 i 个均值
print("X2 - mean_row:\n", centered)
# [[-1.  0.  1.]
#  [-1.  0.  1.]
#  [-1.  0.  1.]
#  [-1.  0.  1.]]
print("每行均值(应≈0):", centered.mean(axis=1))   # [0. 0. 0. 0.] 中心化成功
# 关键点: 若不写 keepdims,mean(axis=1) 是 (4,),拿 (4,3) 减 (4,) 会报错:
try:
    X2 - X2.mean(axis=1)
except ValueError as e:
    print("不写 keepdims 故意报错:", e)
# 报错原文: operands could not be broadcast together with shapes (4,3) (4,)
# 因为 (4,3) 和 (4,) 从右往左对齐是 3 vs 4 → 对不上。
# 补救: keepdims=True 变成 (4,1),1 会被"复制"成 3 → (4,3) 减 (4,1) 就合法了。
# 【怎么读】"每行算一个数,还想减回每行" → 十有八九要 keepdims=True。

# ============================================================
# 六、常见陷阱
# ============================================================
# 陷阱 1:广播对齐"从右往左",别从左往右看
#   (3,2) 加 (3,) 为什么错?因为最右边是 2 和 3,不相等也没有 1 → 报错。
#   想加"每一行的偏移",偏移形状必须是 (2,),不是 (3,)。
#
# 陷阱 2:形状能广播 ≠ 加对了地方
#   (100,784) 的像素图,想"每张图减掉这张图自己的均值":
#     错:图 - 整批图的均值(一个标量)→ 变成减全局均值,不是每张自己的
#     对:mean(axis=1, keepdims=True) → 形状 (100,1),每行减自己的 → 例题4 那种
#
# 陷阱 3:忘了写 axis → 全数组揉成一个数
#   想算"每个人的总分"却写成 np.sum(表) → 得到全班总分一个数。
#   按行/按列算,必须写 axis。写之前想:我要"竖着压(0)"还是"横着压(1)"。
#
# 陷阱 4:把 axis=0 记成"第 0 行"
#   axis 是"第几号维度",不是"第几行"!
#   (3,3) 的 axis=0 是把"行方向"压掉 → 结果 3 个数,是"每列"的总和。
#   记法:结果形状 = 原形状删掉第 axis 个数字。
#
# 陷阱 5:整数数组直接除,信息全丢
#   像素 px 是整数,px / 255.0 才对;写 px // 255 → 全是 0/1,灰阶全没了。
#   想保留小数,除的数要带 .0,或先把数组转 float。
#
# 陷阱 6:忘 seed,实验结果不可复现
#   随机代码没设 np.random.seed(整数) → 每次跑结果都不一样,说不清论文/作业数字。
#   固定 seed,还要保证它出现在所有随机操作【之前】。
#
# 陷阱 7:shuffle 是原地打乱,别拿它的返回值
#   np.random.shuffle(a) 改的是 a 本身,返回 None → print(np.random.shuffle(a)) 打出 None。
#   想要"新的乱序数组、原数组不动" → 用 np.random.permutation。

