#   ★ 聚合函数   → 求和/平均/最大最小,算一批数据的统计量
#   ★ 随机函数   → 造数据、造权重、打乱顺序(训练前必须洗牌)
#   ★ 归一化     → 把像素 0~255 压到 0~1,网络才好训练(MNIST 前处理的核心)
#
# ⚠ 今天不学新语法,全是在 NumPy 里"怎么把一批数算得快"的招,
