import numpy as np

# ============================================================
# 一、广播 Broadcasting:让形状不一样也能直接算(核心!重点)
# ============================================================
# 【为什么需要它】昨天加偏置是  h = W1 @ x + b1(一张图)。
#   今天改成一批图:X(100,784) @ W1(784,64) → (100,64)。
#   但偏置 b1 只有 64 个数,形状是 (64,),和 (100,64) 根本不一样,怎么加?
#   答案:广播。NumPy 会自动把 b1 "复制"成 100 份,让每一行都加上同一个 b1。
print("\n--- 动机: 一批图一起算 ---")
np.random.seed(0)
X = np.random.rand(3, 4)          # 先模拟 3 张"图",每张 4 像素(数字小,方便看)
W1 = np.random.randn(4, 2)        # 权重: 4个像素 → 2个神经元
b1 = np.random.randn(2)           # 偏置: 只有 2 个数
print("X(3,4) @ W1(4,2) 形状 =", (X @ W1).shape)   # (3, 2)
H = X @ W1 + b1                                    # 一批图 + 偏置: 靠广播自动复制
print("(3,2) + b1(2,) 形状 =", H.shape)            # (3, 2)
#   (3,2) 和 (2,) 形状不一样 → 但 NumPy 自动把 b1 复制到 3 行上,照样能加
#   【怎么读】(3,2) 加 (2,): b1 表示"每个神经元的偏置",每张图都该加它 → 广播正好做这事

# ------------------------------------------------------------------
# 广播的两条规则(背下来,就全懂了):
#   规则1: 两个形状【从右往左】一位一位对齐(右端对齐,像竖式加法)
#   规则2: 对齐的两个数,必须【相等】或【其中一个是 1】;满足就自动"复制"补齐;
#          否则直接报错。
# ------------------------------------------------------------------
print("\n--- 规则演示: 小数字看得清 ---")
a = np.array([[1., 2.],
              [3., 4.],
              [5., 6.]])          # (3,2)  3 个样本,每个 2 个特征
v = np.array([10., 20.])          # (2,)   2 个特征各自的偏移
print("a(3,2):\n", a)
print("v(2,):", v)
#   对齐:  (3, 2)
#          (   2)
#          ↑ 2 和 2 相等 → 合法;再把 v 复制 3 份 → 每行都加 [10, 20]
print("a + v:\n", a + v)          # 第0行 [1,2]+[10,20]=[11,22],第1、2行同理
# [[11. 22.]
#  [13. 24.]
#  [15. 26.]]
# 【怎么读】"向量 + 每行都来一遍",这就是偏置 b1 加法的真面目。

# 情况2: 加一个【标量】(只有一个数)
print("a + 100:\n", a + 100)      # 100 复制到每个位置
# [[101. 102.]
#  [103. 104.]
#  [105. 106.]]

# 情况3: 一列 + 一行 → 拼出整张表(二维广播,稍后归一化会用到这种感觉)
col = np.array([[100.], [200.], [300.]])    # (3,1)  "每一行都不同"的数
row = np.array([[1., 2., 3.]])              # (1,3)  "每一列都不同"的数(1行3列)
print("\ncol(3,1):\n", col)
print("row 形状:", row.shape, " 值:", row)   # (1,3)  1行3列
#   对齐:  (3, 1)
#          (1, 3)
#          ↑ 第1维 1 和 3:有 1 → 复制成 3 份;第0维 3 和 1:有 1 → 复制成 3 份 → 结果 (3,3)
print("col + row:\n", col + row)   # 每个位置 = 自己的行数 + 自己的列数 → 结果形状 (3,3)
# [[101. 102. 103.]
#  [201. 202. 203.]
#  [301. 302. 303.]]

# 情况4: 对不上 → 报错
#   (3,2) 加 (3,):对齐看 2 和 3 —— 不相等、也没有 1 → 报错!
try:
    bad = np.array([[1., 2.], [3., 4.], [5., 6.]]) + np.array([10., 20., 30.])
except ValueError as e:
    print("\n故意报错(广播对不上):", e)
# 报错原文: operands could not be broadcast together with shapes (3,2) (3,)
# 翻译: (3,2) 和 (3,) 没法一起广播 → 最右边的 2 和 3 谁也吞不了谁
# 【怎么读】看到这种报错别慌:对齐从右往左,检查是不是"相等或有一个是 1"。

# ============================================================
# 二、聚合函数:np.sum / mean / max / min / argmax(统计一批数)
# ============================================================
# 参数顺序标注(新函数,都是同一个套路):
#   np.sum(①数组, ②axis=None, ③keepdims=False)
#   np.mean(①数组, ②axis=None, ③keepdims=False)
#   np.max(①数组, ②axis=None)      np.min(①数组, ②axis=None)
#   np.argmax(①数组, ②axis=None)
# 【怎么读】axis = "沿哪个方向压扁"。
#   axis 不写 → 全数组揉成一个数(比如全班 9 个成绩加起来)。
#   axis=0   → 把第 0 号维度"压没":(3,3) 按列压 → 得到 3 个数,每个=一列的总和。
#   axis=1   → 把第 1 号维度"压没":(3,3) 按行压 → 得到 3 个数,每个=一行的总和。
# 速记: 结果形状 = 原形状【删掉第 axis 个数字】。
#   (3,3) 删掉第 0 个 → (3,);删掉第 1 个 → (3,)。想知道压的是谁,换个 (2,3) 试:删第0个→(3,)、删第1个→(2,)。
print("\n--- 聚合: 一个班的成绩表 ---")
g = np.array([[90., 85., 92.],     # 学生0: 语 数 英
              [78., 88., 70.],     # 学生1
              [95., 60., 80.]])    # 学生2
print("g(3个学生 × 3科):\n", g)
print("np.sum(g) 全部 =", np.sum(g))                # 全班 9 个分数加起来 → 738.0
print("np.sum(g, axis=0) =", np.sum(g, axis=0))     # 每科的总分(竖着压):[263 233 242]
print("np.sum(g, axis=1) =", np.sum(g, axis=1))     # 每个学生的总分(横着压):[267 236 235]
print("np.mean(g, axis=0) =", np.mean(g, axis=0))   # 每科的平均分 → [87.67 77.67 80.67]
print("np.max(g, axis=0) =", np.max(g, axis=0))     # 每科最高分 → [95 88 92]
print("np.min(g, axis=1) =", np.min(g, axis=1))     # 每人最低的一科 → [85 70 60]
# 手算验证 axis=0 第 0 科: 90+78+95 = 263 ✓(所以 axis=0 = "一列一列往下加")
#          axis=1 第 0 人: 90+85+92 = 267 ✓(所以 axis=1 = "一行一行往右加")

# ------------------------------------------------------------------
# ★ np.argmax:神经网络"猜数字"就靠它(重点)
# ------------------------------------------------------------------
# argmax = 返回"最大值在哪个位置(下标)"。
# 神经网络最后会输出 10 个概率(0~9 每个数一个),"猜它是几"= 找概率最大的下标。
probs = np.array([[0.1, 0.05, 0.7, 0.15],   # 图0: 4 个类别的概率,最大的是 0.7
                  [0.4, 0.3, 0.2, 0.1]])    # 图1: 最大的是 0.4
print("\nprobs(2张图 × 4类):\n", probs)
print("np.argmax(probs, axis=1) =", np.argmax(probs, axis=1))   # [2 0]
# 图0 概率最大的是下标 2 → 猜"2";图1 最大的是下标 0 → 猜"0"
# 【怎么读】argmax(数组, axis=1) = "每一行里,最大的数在第几个位置"
# Day 25 的代码测试专用.py 里你已经见过它: int(np.argmax(z2)) ← 就是猜数字!

# ------------------------------------------------------------------
# ★ keepdims=True:压扁时"留个壳",好让结果还能广播(重点,例题4 会用到)
# ------------------------------------------------------------------
s = np.array([[1., 2., 3.],
              [4., 5., 6.]])        # (2,3)
m1 = np.mean(s, axis=1)             # 每行均值,形状 (2,)
m2 = np.mean(s, axis=1, keepdims=True)   # 形状 (2,1):1 还留着
print("\ns:\n", s)
print("mean(axis=1) 形状:", m1.shape, "值:", m1)              # (2,)   [2. 5.]
print("mean(axis=1, keepdims=True) 形状:", m2.shape)          # (2, 1)
print("keepdims 的值:\n", m2)                                  # [[2.],[5.]]
# 【怎么读】keepdims=True = "算完别把这一维删掉,给它留个 1 的位置"。
#   (2,3) 每行均值本来是 2 个数;留壳后是 (2,1) —— 形状能跟原数组 (2,3) 对齐做广播。

# ============================================================
# 三、随机函数 np.random:造数据 / 造权重 / 打乱顺序
# ============================================================
# 为什么训练要随机:
#   ① 权重 W 一开始不能全 0(全 0 网络学不动),要随机初始化;
#   ② 训练前要把数据顺序打乱(不然网络会"背顺序"而不是学特征);
#   ③ 想复现实验结果,就得用同一个"随机种子"。
# 参数顺序标注:
#   np.random.seed(①种子)              把随机数"存档",下次同种子 → 同结果
#   np.random.rand(①形状)              均匀随机,范围 [0,1)(含0不含1),造"0~1的数据"
#   np.random.randn(①形状)             标准正态(均值0、方差1),造"权重"最常用
#   np.random.randint(①最小值, ②最大值, ③size=None)  整数随机,[最小值, 最大值)
#   np.random.choice(①备选池, ②size=None, ③replace=True, ④p=None)  从池里抽
#   np.random.permutation(①数组/整数)   返回一个乱序的新数组/乱序下标
#   np.random.shuffle(①数组)           原地打乱(把原数组顺序改掉,不返回新数组)

# ★ seed:让随机"可复现"
np.random.seed(42)
r1 = np.random.rand(3)
np.random.seed(42)                    # 再设一次同样的种子
r2 = np.random.rand(3)
print("\n--- 随机: seed 复现 ---")
print("seed(42)+rand(3):", r1)                 # [0.37454012 0.95071431 0.73199394]
print("再 seed(42)+rand(3):", r2)              # 一模一样
print("两次一样吗?", (r1 == r2).all())          # True
# 【怎么读】seed 像"存档点":先存(42)再读档,吐出的随机数序列完全一样。
#   实验要能复现,就固定 seed;同一段代码,别人跑也能得到你的数字。

# ★ randn:造权重(昨天 W1 = np.random.randn(...) 就是这么来的)
np.random.seed(42)
print("seed(42)后 randn(2,3):\n", np.random.randn(2, 3))
# [[ 0.49671415 -0.1382643   0.64768854]
#  [ 1.52302986 -0.23415337 -0.23413696]]
# 有正有负、大多在 -3~3 之间 → 这就是"随机权重"的样子

# ★ randint:造"像素图"(0~255 的整数,像真的图片数据)
img = np.random.randint(0, 256, size=(3, 4))   # 3x4 的小"图",每个像素 0~255
print("randint(0,256,(3,4)):\n", img)
print("这张'小图'min/max:", img.min(), img.max())   # 像素都在 0~255 里
# 【怎么读】randint(①最小, ②最大, ③size) → 取整数,范围 [最小, 最大) → 想取到 255,最大就写 256

# ★ choice / permutation / shuffle:抽样与打乱
pool = np.array([10, 20, 30, 40, 50])
print("choice(pool, size=3):", np.random.choice(pool, size=3))   # 默认可重复抽取 → [40 20 40]
idx = np.random.permutation(5)
print("permutation(5):", idx)                  # 0~4 的乱序 → [3 2 1 0 4]
arr5 = np.arange(5) * 10
np.random.shuffle(arr5)
print("shuffle 后 arr5:", arr5)                # 原地打乱 → [10 20  0 30 40]
# permutation vs shuffle 的区别:
#   permutation(5)  → 返回"乱序下标",原数组不动 → 常用 arr[乱序下标] 来洗牌
#   shuffle(arr)    → 直接把 arr 本身的顺序打乱(返回 None,别 print 它!)

# ============================================================
# 四、归一化:把像素 0~255 压到 0~1(MNIST 前处理的核心)
# ============================================================
# 【为什么必须归一化】像素是 0~255 的大数字,权重却是 -3~3 的小数字:
#   神经元得分 = 权重 @ 像素 → 几百的大数,学习时一步就"震飞",网络很难训练。
#   把像素都除以 255,压到 [0,1],和权重同一量级,网络才学得动。
#   MNIST 的标准前处理就是一句: img / 255(以后 Day 30 你会亲手做)。
print("\n--- 归一化: 除法是最简单的归一化 ---")
px = np.array([[0, 128, 255],
               [51, 102, 153]], dtype=np.uint8)   # 像素本来就是整数,uint8 更像真图
print("像素 px(0~255):\n", px)
n = px / 255.0
print("px / 255.0:\n", n)
# [[0.         0.50196078 1.        ]
#  [0.2        0.4        0.6       ]]
print("类型:", n.dtype, " 范围:", n.min(), "~", n.max())   # float64,0.0 ~ 1.0
# 0/255=0、255/255=1 → 全图都在 [0,1] 里。除的时候要写 255.0(浮点)!
print("陷阱演示 px // 255(整数除):\n", px // 255)
# [[0 0 1]
#  [0 0 0]]   ← 128//255=0、102//255=0,全被砍成 0/1,信息全丢 → 别用整数除!
# 【怎么读】// 是整除,小数全没了;归一化要的是"小数",必须用 / 255.0。

# ★ 另一种常用:min-max 归一化(数据不是 0~255 时用)
#   公式: (x - 最小值) / (最大值 - 最小值)  → 结果一定在 [0,1]
z = np.array([[2., 4., 8.]])
mm = (z - z.min()) / (z.max() - z.min())     # (8-2)=6 当分母
print("min-max 归一化 [[2,4,8]]:", mm)
# [[0.         0.33333333 1.        ]]   ← 2→0、4→0.333、8→1
# 这里 z.min()、z.max() 都是"一个数"(标量),拿标量去减/除整个数组 → 靠的正是广播!
# (以后 Day 30+ 还会见到"标准化":(x-均值)/标准差,先把除255和min-max记住就够)

