# ============================================================
# 一、集合是什么
# ============================================================
# 集合是"无序的、不重复的"元素集合
# 特点：自动去重、支持数学集合运算、元素必须是不可变的

# 创建集合
s1 = {1, 2, 3, 4, 5}
s2 = set()                     # 空集合（注意：{} 是空字典，不是空集合）
s3 = set([1, 2, 2, 3, 3, 4])  # 从列表创建，自动去重 → {1, 2, 3, 4}
s4 = set("hello")              # 从字符串创建 → {"h", "e", "l", "o"}

# 区分 {} 是字典还是集合？
# 有冒号的是字典：{"a": 1}
# 没有冒号的是集合：{1, 2, 3}


# ============================================================
# 二、添加与删除
# ============================================================
s = {1, 2, 3}

# add() — 添加元素
s.add(4)               # {1, 2, 3, 4}
s.add(2)               # {1, 2, 3, 4}  重复的不会被添加

# remove() — 删除元素（不存在会报错）
s.remove(3)            # {1, 2, 4}
# s.remove(99)          ❌ KeyError！

# discard() — 删除元素（不存在不会报错）
s.discard(99)          # ✅ 不会报错
s.discard(4)           # {1, 2}

# pop() — 随机删除一个元素并返回
val = s.pop()          # 集合无序，所以是"随机"删一个
print(val, s)          # 比如 1  {2}

# clear() — 清空
s.clear()              # set()


# ============================================================
# 三、集合运算（重点）
# ============================================================
a = {1, 2, 3, 4}
b = {3, 4, 5, 6}

# 并集 — 两个集合的所有元素（去重）
a | b                  # {1, 2, 3, 4, 5, 6}
a.union(b)             # 同上

# 交集 — 两个集合共有的元素
a & b                  # {3, 4}
a.intersection(b)      # 同上

# 差集 — 在 a 中但不在 b 中的元素
a - b                  # {1, 2}
a.difference(b)        # 同上

# 对称差集 — 两个集合中不重叠的元素
a ^ b                  # {1, 2, 5, 6}
a.symmetric_difference(b)  # 同上

# 判断子集
{1, 2}.issubset(a)     # True   — {1, 2} 是 a 的子集
a.issuperset({1, 2})   # True   — a 包含 {1, 2}
a.isdisjoint({7, 8})   # True   — 两个集合没有交集


# ============================================================
# 四、集合常用操作
# ============================================================
s = {3, 1, 4, 1, 5, 9, 2, 6}

# 去重（集合天生去重）
print(s)               # {1, 2, 3, 4, 5, 6, 9}  但不保证顺序

# 判断元素是否存在
3 in s                 # True
10 in s                # False

# 长度
len(s)                 # 7

# 遍历
for x in s:
    print(x)

# 转列表
list(s)                # [1, 2, 3, 4, 5, 6, 9]

# 转元组
tuple(s)               # (1, 2, 3, 4, 5, 6, 9)


# ============================================================
# 五、集合 vs 列表 对比
# ============================================================
# 集合的优势：去重、集合运算（交集/并集/差集）、查找速度快
# 集合的限制：无序、不能有重复、不能存可变元素（不能存列表/字典）

# 列表切菜，集合查重
items = [3, 1, 2, 1, 3, 4, 2, 5]

# 用集合去重
unique = list(set(items))      # [1, 2, 3, 4, 5]  但不保证顺序

# 用 dict.fromkeys 去重并保持顺序
unique_ordered = list(dict.fromkeys(items))  # [3, 1, 2, 4, 5]


# ============================================================
# 六、集合推导式
# ============================================================
# 和列表推导式类似，只是用 {} 包起来（而且没有冒号）

# 基本
{x**2 for x in range(5)}            # {0, 1, 4, 9, 16}

# 加条件
{x for x in range(20) if x % 3 == 0}  # {0, 3, 6, 9, 12, 15, 18}

# 实际应用：找出两个列表的公共元素
list1 = [1, 2, 3, 4, 5]
list2 = [3, 4, 5, 6, 7]
common = {x for x in list1 if x in list2}
print(common)                        # {3, 4, 5}


# ============================================================
# 七、经典应用场景
# ============================================================

# 场景 1：快速去重
names = ["张三", "李四", "张三", "王五", "李四"]
unique_names = set(names)
print(unique_names)                  # {"张三", "李四", "王五"}

# 场景 2：找出两个列表的差异
old = {"张三", "李四", "王五"}
new = {"李四", "王五", "赵六"}

added = new - old                    # {"赵六"}   新人
removed = old - new                  # {"张三"}   离开的人
both = old & new                     # {"李四", "王五"}  都在的

print(f"新增: {added}, 离开: {removed}, 都在: {both}")

# 场景 3：用集合快速查找（比列表快得多）
# 成员检查：set 是 O(1)，list 是 O(n)
# 从大量数据中判断某个元素是否存在，集合比列表快很多

import time
# 导入 time 模块，用来计算代码运行时间
big_list = list(range(1000000))
# 创建一个包含 0~999999 的列表，共 100 万个元素
big_set = set(big_list)
# 把列表转成集合，得到同样的 100 万个元素

# 列表查找
start = time.time()
# 记录当前时间（开始计时）
999999 in big_list
# 在列表中查找 999999 是否存在
print("列表查找:", time.time() - start)
# 打印"列表查找: 花费的时间"

# 集合查找
start = time.time()
# 记录当前时间（开始计时）
999999 in big_set
# 在集合中查找 999999 是否存在
print("集合查找:", time.time() - start)
# 打印"集合查找: 花费的时间"


# ============================================================
# 八、冻结集合 frozenset（了解）
# ============================================================
# frozenset 是不可变的集合，可以作为字典的 key
# 普通集合不能作为字典的 key，因为它是可变的

fs = frozenset([1, 2, 3])
d = {fs: "这是一个不可变集合"}
print(d)               # {frozenset({1, 2, 3}): "这是一个不可变集合"}


# ============================================================
# 九、常见陷阱
# ============================================================

# 陷阱 1：{} 是空字典，不是空集合
d = {}                 # 这是空字典
s = set()              # 这才是空集合

# 陷阱 2：集合不能包含可变元素
