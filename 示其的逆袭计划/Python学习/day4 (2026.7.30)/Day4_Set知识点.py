# 但元组可以
s = {(1, 2), (3, 4)}   # ✅ 元组不可变，可以

# 陷阱 3：集合无序，不要依赖顺序
# 每次打印集合，元素的顺序可能不同
# 如果需要有序去重，用 dict.fromkeys()
