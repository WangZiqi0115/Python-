# ============================================================
# 七、程序健壮性（防御式编程）
# ============================================================
# 好的程序不只处理"正常情况"，还要处理"异常情况"
#
# 1. 文件不存在 → try/except FileNotFoundError
# 2. 用户输入空值 → if not name: 提示重新输入
# 3. 用户输入非数字 → try/except ValueError
# 4. 删除不存在的联系人 → get 判断
# 5. 重复添加 → 提示已存在 / 覆盖
#
# 这些"边界情况"是写项目最容易漏的，
# 也是面试和实际工作中最看重的。


