# ============================================================
# 二、项目开发的标准套路
# ============================================================
# 1. 先想清楚"要做什么功能"（需求）
# 2. 把功能拆成小函数（每个函数只做一件事）
# 3. 主程序用菜单把函数串起来
# 4. 测试每个函数
# 5. 反复使用、修 bug
#
# 核心思想：模块化 + 函数化
#   每个功能一个函数 → 独立、可复用、好调试


