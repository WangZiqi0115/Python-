# ============================================================
# 一、字典是什么
# ============================================================
# 字典是"键值对"的集合——通过 key 找 value，像查真字典一样
# key 必须是不可变的（字符串、数字、元组），value 可以是任何类型
# 字典是无序的（Python 3.7+ 实际有序，但不要依赖）

# 创建字典
d1 = {"name": "示其", "age": 18, "city": "重庆"}
d2 = {}                         # 空字典
d3 = dict(name="示其", age=18)  # 用 dict() 创建
d4 = dict([("a", 1), ("b", 2)]) # 从元组列表创建

# 注意：{} 是字典，不是集合
# 集合用 {} 但没有冒号：{1, 2, 3} 是集合
# 字典用 {} 且有冒号：{"a": 1} 是字典


# ============================================================
# 二、访问与取值
# ============================================================
d = {"name": "示其", "age": 18, "city": "重庆"}

# 方式 1：方括号取值（key 不存在会报错 KeyError）
d["name"]          # "示其"
# d["score"]        ❌ KeyError，因为 "score" 不存在

# 方式 2：get() 安全取值（key 不存在返回 None，不会报错）
d.get("name")      # "示其"
d.get("score")     # None
d.get("score", 0)  # 0  — 可以指定默认值

# 判断 key 是否存在
"name" in d        # True
"score" in d       # False


# ============================================================
# 三、增删改
# ============================================================
d = {"name": "示其", "age": 18}

# 添加 / 修改（同一个语法）
d["city"] = "重庆"     # key 不存在 → 新增：{"name": "示其", "age": 18, "city": "重庆"}
d["age"] = 19          # key 已存在 → 修改：{"name": "示其", "age": 19, ...}

# 删除
del d["age"]           # 删除 key 为 "age" 的键值对
# d.pop("age")         # 删除并返回被删的值（类似 list.pop）

# 清空
# d.clear()            # 清空所有键值对


# ============================================================
# 四、遍历字典
# ============================================================
d = {"name": "示其", "age": 18, "city": "重庆"}

# 遍历 key
for k in d:
    print(k)           # name  age  city

# 遍历 value
for v in d.values():
    print(v)           # 示其  18  重庆

# 遍历 key 和 value（最常用）
for k, v in d.items():
    print(k, v)        # name 示其    age 18    city 重庆


# ============================================================
# 五、常用方法速查
# ============================================================
d = {"a": 1, "b": 2, "c": 3}

d.keys()              # dict_keys(["a", "b", "c"])    所有 key
d.values()            # dict_values([1, 2, 3])        所有 value
d.items()             # dict_items([("a",1), ("b",2), ("c",3)])  所有键值对
d.get("a")            # 1       安全取值
d.get("x", 0)         # 0       不存在时返回默认值
d.update({"d": 4})    # {"a":1, "b":2, "c":3, "d":4}  合并另一个字典
# d.pop("a")          # 1       删除 key"a"并返回值
# d.popitem()         # ("d",4) 删除并返回最后一对


# ============================================================
# 六、字典推导式
# ============================================================
# 和列表推导式类似，但用 {} 包起来

# 基本
{x: x**2 for x in range(5)}      # {0:0, 1:1, 2:4, 3:9, 4:16}

# 加条件
{x: x**2 for x in range(10) if x % 2 == 0}  # {0:0, 2:4, 4:16, 6:36, 8:64}

# 反转 key 和 value
d = {"a": 1, "b": 2, "c": 3}
{v: k for k, v in d.items()}     # {1:"a", 2:"b", 3:"c"}


