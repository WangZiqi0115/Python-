# ============================================================
# 二、星号解包 *（重点）
# ============================================================
# 数量不确定时，用 * 把"剩下的全部"收集成一个列表

# 1. 开头固定，其余全部收集：
a, *rest = [1, 2, 3, 4]
# a = 1, rest = [2, 3, 4]

# 2. 开头和结尾都固定：
a, *middle, b = [1, 2, 3, 4, 5]
# a = 1, middle = [2, 3, 4], b = 5

# 3. 结尾固定，开头全部收集：
*head, last = [1, 2, 3, 4]
# head = [1, 2, 3], last = 4

# 4. 字符串也可以：
first, *others = "hello"
# first = 'h', others = ['e', 'l', 'l', 'o']

# 5. 没剩东西时，* 收集到空列表：
a, *rest = [1]
# a = 1, rest = []

# 注意：
#   * 收集的结果永远是 list（不是 tuple）
#   一次赋值里只能有一个 *：a, *b, *c = ... 会报错


# ============================================================
# 三、星号解包的实用场景
# ============================================================
# 1. 取第一个和最后一个，忽略中间：
nums = [10, 20, 30, 40, 50]
first_num, *_, last_num = nums
# first_num = 10, last_num = 50，_ 表示"我不关心中间"

# 2. 丢弃不用的值：
_, score = ("张三", 95)
# 第一个值不要，用 _ 占位

# 3. 拆分出"头部"和"剩余部分"（递归/刷题常用）：
head, *tail = [1, 2, 3, 4]
# head = 1, tail = [2, 3, 4]

# 4. 在 for 循环里解包不等长数据：
data_list = [(1, 2, 3), (4, 5, 6)]
for a, *rest in data_list:
    print(a, rest)
# 1 [2, 3]
# 4 [5, 6]


# ============================================================
# 四、嵌套解包
# ============================================================
# 容器的容器也可以按结构直接拆开：
(a, (b, c)) = (1, (2, 3))
# a = 1, b = 2, c = 3

# 列表套元组：
[x, (y, z)] = [10, (20, 30)]
# x = 10, y = 20, z = 30

# 和 Day 15 的嵌套数据配合：
people = [
    ("张三", {"city": "重庆", "age": 18}),
    ("李四", {"city": "北京", "age": 19}),
]
for name, info in people:
    print(name, info["city"])
# 张三 重庆
# 李四 北京


# ============================================================
# 五、调用解包 *args / **kwargs（重点）
# ============================================================
# 星号不仅能出现在赋值左边，还能出现在"函数调用"里

# 1. 调用时用 *，把列表/元组拆成"位置参数"：
def add(a, b, c):
    return a + b + c

nums = [1, 2, 3]
print(add(*nums))          # 6，等价于 add(1, 2, 3)

# 2. 调用时用 **，把字典拆成"关键字参数"：
def show(name, age):
    return f"{name}-{age}"

info = {"name": "张三", "age": 18}
print(show(**info))        # 张三-18，等价于 show(name="张三", age=18)

# 3. 混合使用：
#    func(1, *[2, 3], **{"x": 4})

# 4. 内置函数也支持：
print(*[1, 2, 3])          # 1 2 3
print(*range(5))           # 0 1 2 3 4

# 5. 合并字典（Python 3.9 前的经典写法）：
d1 = {"a": 1, "b": 2}
d2 = {"b": 3, "c": 4}
merged = {**d1, **d2}
# merged = {'a': 1, 'b': 3, 'c': 4}，后面覆盖前面


# ============================================================
# 六、zip(*data) 转置（非常实用）
# ============================================================
# zip 把多个序列"按位置配对"，* 再把它拆开，可以实现转置

pairs = [(1, 4), (2, 5), (3, 6)]
print(list(zip(*pairs)))
# [(1, 2, 3), (4, 5, 6)]

# 二维列表转置：行变列、列变行
matrix = [[1, 2, 3], [4, 5, 6]]
transposed = list(zip(*matrix))
# [(1, 4), (2, 5), (3, 6)]

# 原理：
#   zip(*pairs) 等价于 zip((1,4), (2,5), (3,6))
#   zip 按位置配对：第一个元素放一起 → (1,2,3)


