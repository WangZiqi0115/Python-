# 解包并转换：
labels = [f"{name}:{score}分" for name, score in scores.items()]
# ['张三:95分', '李四:82分']


# ============================================================
# 八、常见陷阱
# ============================================================
# 陷阱 1：变量数量对不上
#   a, b = [1, 2, 3]  ❌ ValueError: too many values to unpack
#   a, b, c = [1, 2]  ❌ ValueError: not enough values to unpack
#   数量不确定时用 * 收集

# 陷阱 2：一个赋值里不能有两个 *
#   a, *b, *c = [1, 2, 3, 4]  ❌ SyntaxError

# 陷阱 3：* 收集的是 list
#   不要以为 rest 是 tuple，它是 [2, 3, 4] 这种列表

# 陷阱 4：调用解包不能乱用
#   func(*nums)：把 nums 拆成位置参数
#   func(**info)：把 info 拆成关键字参数
#   func(**nums) 且 nums 是列表  ❌ TypeError

# 陷阱 5：** 解包的字典键必须是合法参数名
#   info = {"first name": "张三"}  ❌ 不能作为参数名

# 陷阱 6：zip(*matrix) 返回的是元组
#   想得到列表，套一层 [list(row) for row in zip(*matrix)]


