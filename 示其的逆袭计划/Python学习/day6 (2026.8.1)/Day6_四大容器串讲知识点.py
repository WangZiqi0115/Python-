# ============================================================
# 一、四大容器总览对比
# ============================================================
#             有序    可变    可重复   存储方式       适用场景
# 列表 List   ✅      ✅      ✅      按位置        动态数据集合
# 元组 Tuple  ✅      ❌      ✅      按位置        固定不变的数据
# 字典 Dict   ✅(3.7+) ❌key  ✅key    键值对映射    按名字查找
# 集合 Set    ❌      ✅      ❌      无序唯一      去重、集合运算

# 创建方式速记：
# 列表：[]       [1, 2, 3]
# 元组：()       (1, 2, 3)  ← 单元素要加逗号 (1,)
# 字典：{} + 冒号 {"name": "示其"}
# 集合：{} 无冒号 {1, 2, 3}   空集合必须 set()


# ============================================================
# 二、"可变"对比：谁能改，谁不能改
# ============================================================
# 可变：列表、字典、集合 —— 内容可以修改
# 不可变：元组、字符串、数字、布尔值 —— 内容不能修改

# 列表可变（可以直接改）
lst = [1, 2, 3]
lst[0] = 99          # ✅
lst.append(4)        # ✅

# 元组不可变（不能改）
tup = (1, 2, 3)
# tup[0] = 99        ❌ TypeError
# tup.append(4)      ❌ AttributeError

# 字典可变（key 不能改，value 能改）
d = {"name": "示其"}
d["name"] = "张三"   # ✅ value 可以改
d["age"] = 18        # ✅ 可以加新键值对

# 集合可变（能加能删，但元素本身必须是不可变的）
s = {1, 2, 3}
s.add(4)             # ✅
s.remove(2)          # ✅
# s = {[1, 2]}       ❌ 列表不可哈希，不能放集合里


# ============================================================
# 三、常用方法对照表
# ============================================================
# 操作         列表      元组      字典           集合
# 添加         append    ❌        d[k]=v        add
# 插入         insert    ❌        ❌            ❌
# 删除         remove    ❌        del/pop       remove/discard
#              pop                 popitem
# 查找         index     index     d[k]/get      in
# 计数         count     count     ❌            ❌
# 排序         sort      ❌        ❌            ❌
#              sorted()  sorted()  sorted(d)     sorted(s)
# 长度         len       len       len           len
# 遍历         for       for       items()       for
# 切片         ✅        ✅        ❌            ❌
# 推导式       [...]     (...)     {k:v ...}     {...}
# 去重         ❌        ❌        ❌            ✅ 天生去重


# ============================================================
# 四、四大容器的遍历方式
# ============================================================
# 列表遍历
fruits = ["苹果", "香蕉", "橘子"]
for f in fruits:
    print(f)
for i, f in enumerate(fruits):
    print(i, f)

# 元组遍历（和列表一样）
t = (10, 20, 30)
for x in t:
    print(x)

# 字典遍历（key / value / 都遍历）
d = {"name": "示其", "age": 18}
for k in d:                    # 遍历 key
    print(k)
for v in d.values():           # 遍历 value
    print(v)
for k, v in d.items():         # 同时遍历
    print(k, v)

# 集合遍历（无序）
s = {3, 1, 4, 1, 5}
for x in s:
    print(x)


# ============================================================
# 五、什么时候用哪个容器（决策树）
# ============================================================
# 问题 1：需要"按名字"查找数据？
#   是 → 字典
#   否 → 看问题 2
#
# 问题 2：数据需要去重，或者要做交集/并集？
#   是 → 集合
#   否 → 看问题 3
#
# 问题 3：数据创建后还需要修改吗？
#   是 → 列表
#   否 → 元组

# 实战例子：
# 学生分数表（按学号查）      → 字典 {"001": 95}
# 一周七天（固定不变）        → 元组 ("一", "二", "三"...)
# 购物车（要增删改）          → 列表 [item1, item2]
# 用户 ID 列表（要去重）      → 集合 {101, 102, 103}


# ============================================================
# 六、容器之间的转换
# ============================================================
lst = [1, 2, 2, 3]
tup = (1, 2, 3)
d = {"a": 1, "b": 2}
s = {1, 2, 3}

# 转列表
list(tup)              # [1, 2, 3]
list(s)                # [1, 2, 3]
list(d)                # ["a", "b"]      ← 取的是 key
list(d.items())        # [("a", 1), ("b", 2)]

# 转元组
tuple(lst)             # (1, 2, 2, 3)
tuple(s)               # (1, 2, 3)

# 转集合（自动去重）
set(lst)               # {1, 2, 3}
set(d)                 # {"a", "b"}      ← 取的是 key

# 转字典
dict([("a", 1), ("b", 2)])     # {"a": 1, "b": 2}
dict(zip(["a", "b"], [1, 2]))  # {"a": 1, "b": 2}


# ============================================================
# 七、综合应用：学生成绩系统（把四个容器都用上）
# ============================================================
# 需求：
# 1. 学生信息用字典存（学号 → 姓名）
# 2. 成绩单用字典存（学号 → [各科成绩]）
# 3. 班级名单用集合存（去重）
# 4. 班级代号用元组存（固定不变）

class_codes = ("MATH-01", "MATH-02")       # 元组：固定
students = {                               # 字典：按学号查
    "001": {"name": "张三", "scores": [95, 87, 92]},
    "002": {"name": "李四", "scores": [78, 90, 85]},
    "003": {"name": "王五", "scores": [88, 76, 95]},
}
attendance = {"001", "002"}                # 集合：去重、判断在不在
enrolled = list(students.keys())           # 列表：动态处理

# 计算每个学生的平均分
for sid, info in students.items():
    avg = sum(info["scores"]) / len(info["scores"])
    print(f"{info["name"]}: {avg:.1f}分")

# 谁今天没来？
absent = set(students.keys()) - attendance
print("缺勤：", absent)                     # {"003"}

# 成绩排序
rank = sorted(students.items(), key=lambda x: sum(x[1]["scores"]), reverse=True)
for sid, info in rank:
    print(f"{info["name"]}: {sum(info["scores"])}分")


