# 八、一题四用：统计一段文字
# ============================================================
text = "python java python c c++ python java"

# 用列表：按顺序保存所有单词
words_list = text.split()
# ["python", "java", "python", "c", "c++", "python", "java"]

# 用元组：固定不变（比如题目给出的数据）
words_tuple = tuple(text.split())

# 用字典：统计每个单词出现次数
freq = {}
for w in text.split():
    freq[w] = freq.get(w, 0) + 1
# {"python": 3, "java": 2, "c": 1, "c++": 1}

# 用集合：提取不重复的单词
unique_words = set(text.split())
# {"python", "java", "c", "c++"}


# ============================================================
# 九、常见混淆点（重点）
# ============================================================

# 混淆 1：{} 到底是字典还是集合？
{}                       # 字典（空）
{1, 2, 3}                # 集合（无冒号）
{"a": 1}                 # 字典（有冒号）
set()                    # 空集合（唯一写法）

# 混淆 2：元组和列表选哪个？
# 能改 → 列表；不能改 → 元组
# 元组还能当字典的 key，列表不行
d = {}
d[(1, 2)] = "坐标"       # ✅ 元组可以做 key
# d[[1, 2]] = "坐标"     ❌ 列表不能做 key

# 混淆 3：集合和字典的取值方式
# 字典：d["name"] 或 d.get("name")
# 集合：只能用 in 判断，不能按下标取
s = {1, 2, 3}
# s[0]                  ❌ 集合没有下标
1 in s                  # ✅ True

# 混淆 4：排序是否会修改原容器
lst.sort()               # 修改原列表，无返回值
sorted(lst)              # 返回新列表，不修改原列表
# 字典和集合的 sorted() 返回排好序的列表（只有 key）
sorted({"b": 2, "a": 1})    # ["a", "b"]
