# ============================================================
# 一、为什么需要编码（计算机只认识 0 和 1）
# ============================================================
# 计算机底层只有 0 和 1（二进制），那"你好"、"abc"这些文字怎么存？
# 答案：给每个文字编一个"数字编号"，再存成二进制。
#
# 类比：电报/摩斯密码
#   摩斯密码：A → ".-"，B → "-..."，每个字母对应一串符号
#   字符编码：'A' → 65 → 01000001，每个字符对应一个数字
#
# 流程：文字 → 查编码表得到数字 → 存成二进制
#       二进制 → 查编码表还原数字 → 得到文字
#
# 编码表有好几套（ASCII、Unicode、UTF-8、GBK...），
# 存的时候用哪套，读的时候就得用哪套——用错了就乱码（第八节讲）。


# ============================================================
# 二、ASCII：最老的编码表（美国标准）
# ============================================================
# ASCII = American Standard Code for Information Interchange
#         美国信息交换标准代码
# 只包含 128 个字符：英文字母（大小写）、数字、常见标点、控制字符
# 每个字符占 1 个字节（实际用 7 位，最高位是 0）
#
# 必背的几个编号：
#   'A' = 65，'B' = 66，...（大写从 65 开始）
#   'a' = 97，'b' = 98，...（小写从 97 开始）
#   '0' = 48，'1' = 49，...（数字从 48 开始）
#   大小写差 32：'a' - 'A' = 97 - 65 = 32

# Python 里查编号用 ord()，编号转字符用 chr()
print(ord("A"))          # 65
print(ord("a"))          # 97
print(chr(97))           # 'a'
print(chr(65))           # 'A'

# 【补充】ASCII 的局限：只有英文！
#   中文、日文、韩文、emoji 都不在 ASCII 里 → 需要更大的编码表


# ============================================================
# 三、Unicode：全世界字符的"身份证号"
# ============================================================
# Unicode（统一码）：给世界上所有字符一个唯一的"编号"（叫码点 code point）
#   例：'A' 的码点是 U+0041，'你' 的码点是 U+4F60
#   注意：Unicode 只是"编号表"，不规定怎么存成字节！
#
# 类比：每个人都有唯一的身份证号（Unicode 编号），
#       但"身份证号怎么印在纸上"是另一回事（编码方案）

print(ord("你"))         # 20320  = 0x4F60（十六进制）
print(hex(ord("你")))    # 0x4f60


# ============================================================
# 四、UTF-8：最流行的"存储方案"（重点）
# ============================================================
# UTF-8 是 Unicode 的"存储实现"之一，规则：
#   - 英文（ASCII 范围）：1 个字节，和 ASCII 完全兼容
#   - 中文：3 个字节
#   - 其他文字：2 或 4 个字节（变长）
#
# 为什么 UTF-8 最流行？
#   ① 兼容 ASCII：老的英文文件不用转换
#   ② 省空间：英文多的文本比固定 2/4 字节的方案省
#   ③ 无字节序问题（不像 UTF-16 分大小端）
#
# 类比：Unicode 是"全班同学的名单"（编号），
#       UTF-8 是"一种装进快递箱的方式"（存储）

# 看一个中文字符在 UTF-8 下占几个字节：
s = "你"
b = s.encode("utf-8")          # str → bytes（编码）
print(b)                       # b'\xe4\xbd\xa0'   ← 3 个字节
print(len(b))                  # 3     # 一个"你"在 UTF-8 下占 3 字节

# 英文在 UTF-8 下只占 1 字节：
print(len("A".encode("utf-8")))  # 1


# ============================================================
# 五、GBK：中文场景的另一套方案
# ============================================================
# GBK = 国标扩展编码（简体中文常用）
#   - 中文：2 个字节（比 UTF-8 的 3 字节省）
#   - 英文：1 个字节（兼容 ASCII）
#
# GBK 和 UTF-8 互相不兼容！
#   同一个"你"：
#     UTF-8 编码 → b'\xe4\xbd\xa0'（3 字节）
#     GBK 编码   → b'\xc4\xe3'（2 字节）

print("你".encode("utf-8"))   # b'\xe4\xbd\xa0'
print("你".encode("gbk"))     # b'\xc4\xe3'

# 【补充】为什么不都用 GBK？
#   GBK 是"区域性"方案：只覆盖中文场景；换其他语言就抓瞎
#   UTF-8 是"国际通用"：全世界的字符都能表示 → 现代默认都用 UTF-8
#   但历史文件可能是 GBK 存的，读取时要指定 gbk


# ============================================================
# 六、str vs bytes：文字 vs 字节（重点）
# ============================================================
# 两种数据类型，别搞混：
#   str（字符串）  = 给人看的"文字"，是 Unicode 字符的序列
#   bytes（字节串）= 给机器/文件/网络用的"字节"，是 0~255 的整数序列

# 字面量写法：
s = "你好"                # str：双引号/单引号
b = b"hello"             # bytes：前面加 b
print(type(s))           # <class 'str'>
print(type(b))           # <class 'bytes'>

# 【重点】bytes 字面量里只能写 ASCII 字符！
#   b"你好"  ← 会报错 SyntaxError（中文不是 ASCII）
#   中文要先进 str，再 encode 成 bytes

# 【类比】str 是"字"，bytes 是"字的二进制快递"
#   你想把文字发给朋友（写文件/传网络）：
#     先 encode（把字装进快递箱）→ bytes
#     朋友收到后 decode（拆快递箱）→ 还原成字

# bytes 长什么样？索引它得到的是"整数"（字节值）：
print(b"abc")            # b'abc'
print(b"abc"[0])         # 97     ← 整数！不是字符 'a'
print(list(b"abc"))      # [97, 98, 99]


# ============================================================
# 七、encode / decode：打包与拆包（重点）
# ============================================================
# 一对"逆操作"：
#   str.encode(编码) → bytes    文字 → 字节（打包发货）
#   bytes.decode(编码) → str    字节 → 文字（拆包收货）
#
# 参数顺序标注：str.encode(①编码, ②错误处理) / bytes.decode(①编码, ②错误处理)
#   编码参数：'utf-8'（默认）/ 'gbk' / 'ascii' ...
#   不写编码默认 utf-8

s = "你好"
b = s.encode("utf-8")     # 打包：str → bytes
print(b)                  # b'\xe4\xbd\xa0\xe5\xa5\xbd'
print(type(b))            # <class 'bytes'>

back = b.decode("utf-8")  # 拆包：bytes → str
print(back)               # 你好
print(type(back))         # <class 'str'>

# 【补充】默认编码是 utf-8：
print("abc".encode())     # b'abc'   # 等于 encode("utf-8")
print(b"abc".decode())    # 'abc'

# 【补充】encode 编码不对会怎样？
#   "你好".encode("ascii") → UnicodeEncodeError（ASCII 装不下中文）
#   b'\xe4\xbd\xa0'.decode("ascii") → UnicodeDecodeError
#   这些也是异常！可以用昨天学的 try/except 接住


# ============================================================
# 八、乱码原理（重点，终于到正题了）
# ============================================================
# 乱码 = 编码和解码用了不同的"密码本"
#   写文件用 A 编码表 → 读文件用 B 编码表 → B 不认识 A 的字 → 乱码
#
# 类比：你用中文摩斯密码本把"你好"编成电码发出去，
#       对方却用英文摩斯密码本解码 → 得到一堆看不懂的符号

# 演示：同一个"你好"，UTF-8 编码、GBK 解码：
correct = "你好".encode("utf-8")      # 用 UTF-8 打包
print(correct.decode("gbk"))          # 用 GBK 拆包 → 乱码！
# 输出：浣犲ソ    （一堆看不懂的字符）

# 反过来：GBK 编码、UTF-8 解码 → 常常直接报 UnicodeDecodeError！
#   （GBK 的字节序列在 UTF-8 里可能是"非法序列"，解码器直接罢工）
correct2 = "你好".encode("gbk")       # 用 GBK 打包
try:
    print(correct2.decode("utf-8"))   # 用 UTF-8 拆包 → 大概率报错
except UnicodeDecodeError as e:
    print("UnicodeDecodeError：", e)  # 接住！这正是昨天学的异常
# 输出：UnicodeDecodeError：'utf-8' codec can't decode byte 0xc4 ...

# 【补充】乱码有"两种形态"，本质都是"解码表用错"：
#   ① 解码"成功"但显示乱码字符：UTF-8 字节用 GBK 解码（上面的浣犲ソ）
#   ② 直接抛 UnicodeDecodeError：GBK 字节用 UTF-8 解码（字节序列非法）
#   修复方法都一样：用对编码 decode

# 【修复方法】知道原始编码，用对的编码解码：
mojibake = "你好".encode("gbk")       # 假设文件是 GBK 存的
print(mojibake.decode("gbk"))         # 你好    ← 用对编码就还原了

# 【排查思路】
#   1. 看乱码长什么样：���（替换符）说明解码失败；一堆"浣犲ソ"说明用错表
#   2. 问来源：文件/网页/数据库声明的是什么编码
#   3. 用声明的编码 decode，或尝试 utf-8 → gbk → 其他常见编码


# ============================================================
# 九、Python 3 的几个关键点
# ============================================================
# ① 字符串字面量是 str；b"..." 是 bytes 字面量
# ② len() 对 str 数"字符个数"，对 bytes 数"字节个数"：
s = "你好abc"
print(len(s))                       # 5    （2 个字符 + 3 个字符）
print(len(s.encode("utf-8")))       # 9    （中文 3×2 + 英文 1×3 = 9）

# ③ open() 读文件默认按 utf-8 解码：
#   with open("f.txt", encoding="utf-8") as f:  ← 昨天学过的 encoding 参数
#   文件实际编码和 encoding 不一致 → UnicodeDecodeError → 昨天学的异常

# ④ 十六进制和字节的转换：
print("A".encode().hex())           # '41'    # 字节 → 十六进制字符串
print(bytes.fromhex("41").decode()) # 'A'     # 十六进制 → 字节 → 文字


# ============================================================
# 十、例题精讲（看懂了再去做练习）
# ============================================================

# ------------------------------------------------------------
# 例题 1：字符串 → UTF-8 字节 → 还原（完整流程）
# 思路：encode 打包，decode 拆包
# ------------------------------------------------------------
def round_trip(s):
    b = s.encode("utf-8")        # 打包
    back = b.decode("utf-8")     # 拆包
    return back

print(round_trip("你好，Python"))   # 你好，Python
print(len("你好，Python".encode("utf-8")))  # 15
# 算一下：'你'、'好'、'，'（全角逗号）各 3 字节 = 9；'Python' 6 个英文各 1 字节 = 6；共 15
# 关键点：encode 和 decode 用同一编码才能还原

# ------------------------------------------------------------
# 例题 2：字符数 vs 字节数
# 思路：len(str) 数字符，len(str.encode(...)) 数字节
# ------------------------------------------------------------
text = "abc你好"
print(len(text))                          # 5（字符数）
print(len(text.encode("utf-8")))          # 9（字节数：3+2×3）
print(len(text.encode("gbk")))            # 7（字节数：3+2×2）
# 同一句话，不同编码占的字节数不一样 → UTF-8 中文 3 字节，GBK 中文 2 字节

# ------------------------------------------------------------
# 例题 3：乱码的修复
# 思路：先看字节是什么编码，再用对编码 decode
# ------------------------------------------------------------
raw = "示其".encode("gbk")        # 假设从旧系统拿到 GBK 字节
# 误用 utf-8 解码 → 大概率直接抛 UnicodeDecodeError（字节序列非法）
try:
    print(raw.decode("utf-8"))    # 偶尔能解出来，但也是乱码字符
except UnicodeDecodeError as e:
    print("UnicodeDecodeError：", e)
# 用对编码 gbk 解码 → 还原
print(raw.decode("gbk"))          # 示其
# 关键点：乱码不是数据坏了，是"解码表用错了"；用对编码就能还原

# ------------------------------------------------------------
# 例题 4：bytes 和十六进制互转
# 思路：.hex() 转十六进制字符串；bytes.fromhex() 转回
# ------------------------------------------------------------
b = "OK".encode()
print(b)                          # b'OK'
print(b.hex())                    # '4f4b'（O=0x4f, K=0x4b）
print(bytes.fromhex("4f4b"))      # b'OK'
print(bytes.fromhex("4f4b").decode())   # 'OK'
# 关键点：hex() 是字节的"十六进制身份证"，常用于调试、传输


# ============================================================
# 十一、常见陷阱
# ============================================================
# 陷阱 1：bytes 字面量里写中文 → SyntaxError
#   b"你好" 不行；要先 "你好".encode()
#
# 陷阱 2：encode/decode 编码不一致 → 乱码
#   存用 utf-8，读用 gbk → 乱码；统一编码
#
# 陷阱 3：decode 编码不对 → UnicodeDecodeError
#   可以用 try/except UnicodeDecodeError 接住（昨天学的异常）
#
# 陷阱 4：len 的语义搞混
#   len(str) = 字符个数；len(bytes) = 字节个数
#
# 陷阱 5：b"abc"[0] 是整数 97，不是字符 'a'
#   想拿字符：bytes.decode() 后取，或 chr(b"abc"[0])
#
# 陷阱 6：文件 open 忘记指定 encoding
#   文件是 GBK 但没写 encoding="gbk" → 按 utf-8 读 → UnicodeDecodeError
