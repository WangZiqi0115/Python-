# ============================================================
# 八、选择哪种写法？
# ============================================================
# 列表推导式：需要完整结果列表时
# 生成器：数据量大 / 只需要遍历一次时
# lambda：作为参数传给别人时（key=、map、filter）
# 普通 for 循环：逻辑复杂、多行操作时

# 判断标准：一行写得清楚就用推导式；写不清楚就用 for 循环
# 没有"必须用"的规定，代码可读性优先


# ============================================================
# 九、常见陷阱
# ============================================================

# 陷阱 1：推导式里的变量会"泄漏"到外面（旧版本，3.0+已修复）
# Python 3 里推导式有自己的作用域，不用担心

# 陷阱 2：嵌套推导式顺序容易搞反
# 外层 for 在前，内层 for 在后
# [num for row in matrix for num in row]  外层 row，内层 num

# 陷阱 3：lambda 在循环里捕获变量（面试常考）
funcs = [lambda x: x * i for i in range(3)]
# 你以为 funcs[0](5) = 0？其实是 10！
# 因为 lambda 捕获的是变量 i 的"最终值"（循环结束 i=2）
#
# 【补充】funcs[0](5) 的括号是什么意思？
#   funcs[0] 是从列表里"取出第 1 个函数"（它本身是 lambda 函数）
#   (5) 是"调用这个函数"，把 5 传给参数 x
#   所以 funcs[0](5) = 取出函数 → 调用 → x=5 → 5 * i
#   类比：print("hello") 里的 "hello" 就是传给 print 的参数
#   语法格式：函数名(参数)；这里的"函数名"是从列表里取出来的

# 修复：
funcs = [lambda x, i=i: x * i for i in range(3)]
funcs[0](5)        # 0
funcs[1](5)        # 5

# 陷阱 4：生成器只能用一次
gen = (x for x in range(3))
list(gen)    # [0, 1, 2]
list(gen)    # []  已用完

# 陷阱 5：想修改原列表不能用推导式
nums = [1, 2, 3]
nums = [x * 2 for x in nums]    # ✅ 生成新列表再赋值
# nums.sort() 修改原列表
