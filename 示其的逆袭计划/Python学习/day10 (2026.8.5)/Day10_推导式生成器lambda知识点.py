# ============================================================
# 一、四种推导式总览
# ============================================================
# 推导式 = 一行代码生成新容器
# 共同结构：[表达式 for 变量 in 可迭代对象 if 条件]

# 列表推导式 → 生成列表
[x**2 for x in range(5)]              # [0, 1, 4, 9, 16]

# 字典推导式 → 生成字典（用 {} 且有冒号）
{x: x**2 for x in range(5)}           # {0:0, 1:1, 2:4, 3:9, 4:16}

# 集合推导式 → 生成集合（用 {} 没有冒号）
{x % 3 for x in range(10)}            # {0, 1, 2}

# 生成器表达式 → 生成生成器（用 ()）
(x**2 for x in range(5))              # <generator object ...>

# 【补充】生成器表达式怎么用？
#   1. 转列表：list(gen)
#   2. for 遍历：for v in gen: ...
#   3. 传给 sum/max/any/all：sum(x**2 for x in range(5))
#   4. next(gen) 手动取下一个值（用完报 StopIteration）
#   它"懒"：不立刻算出所有结果，遍历时才一个一个给，省内存


# ============================================================
# 二、生成器是什么（重点）
# ============================================================
# 生成器 = 惰性计算的"流水线"，不一次性生成所有结果
# 用的时候才逐个产生，省内存

# 对比列表和生成器：
import sys

big_list = [x for x in range(1000000)]       # 列表：立刻算出100万个
big_gen = (x for x in range(1000000))        # 生成器：先不算，用的时候再给

sys.getsizeof(big_list)    # 大约 8MB（100万个数字都存着）
sys.getsizeof(big_gen)     # 大约 112B（几乎不占内存）

# 怎么取出生成器的值？
gen = (x**2 for x in range(5))
list(gen)                  # [0, 1, 4, 9, 16]  转成列表
next(gen)                  # 0  逐个取（但上面已用完，这里会报 StopIteration）
for x in gen:              # 可以遍历
    print(x)

# 注意：生成器只能用一次，用完了就没了
gen = (x for x in range(3))
list(gen)                  # [0, 1, 2]
list(gen)                  # []  第二次是空的！

# 【补充】为什么是一次性的？
#   生成器不存储结果，像"单向前进的传送带"：走过就没了
#   列表像"书架"：内容一直放着，可以反复翻
#   需要多次使用 → 每次重新创建生成器，或改用列表推导式


# ============================================================
# 三、yield 生成器函数（进阶）
# ============================================================
# 用 def + yield 也能创建生成器
# yield = "暂停并交出值，下次调用继续"

def count_down(n):
    while n > 0:
        yield n          # 交出 n，暂停
        n -= 1

for x in count_down(3):
    print(x)             # 3 2 1

# 对比 return：return 结束函数，yield 暂停函数
# 每次 for 循环要下一个值时，函数从上次 yield 的地方继续


# ============================================================
# 四、lambda 匿名函数（重点）
# ============================================================
# lambda = 一行写一个简单函数
# 格式：lambda 参数: 返回值

# 普通函数 vs lambda：
def add(a, b):
    return a + b

add_lambda = lambda a, b: a + b    # 等价

add(3, 5)          # 8
add_lambda(3, 5)   # 8

# lambda 的真正用途：作为参数传给其他函数
students = [("张三", 95), ("李四", 82)]
sorted(students, key=lambda x: x[1], reverse=True)   # 按分数排

max(students, key=lambda x: x[1])                    # 最高分学生

# 也可以用于列表推导式的表达式部分
nums = [1, 2, 3, 4]
square = list(map(lambda x: x**2, nums))             # [1, 4, 9, 16]
even = list(filter(lambda x: x % 2 == 0, nums))      # [2, 4]

# lambda 的限制：只能写一个表达式，不能有 if/for/多行逻辑
# lambda x: if x > 0: ...    ❌ 语法错误


# ============================================================
# 五、推导式进阶：嵌套
# ============================================================
# 嵌套推导式 = 等价于嵌套 for 循环
# 外层 for 写在前面，内层 for 写在后面

# 二维列表扁平化
matrix = [[1, 2], [3, 4], [5, 6]]
flat = [num for row in matrix for num in row]
# [1, 2, 3, 4, 5, 6]
#
# 执行过程详解：
# 第一个 for row in matrix 是"外层循环"，先取出每一个小列表：
#   row = [1, 2]     （matrix 的第 0 个元素）
#   row = [3, 4]     （matrix 的第 1 个元素）
#   row = [5, 6]     （matrix 的第 2 个元素）
#
# 第二个 for num in row 是"内层循环"，把当前小列表里的每个数取出来：
#   row = [1, 2]  → num = 1, 2
#   row = [3, 4]  → num = 3, 4
#   row = [5, 6]  → num = 5, 6
#
# 最前面的 num 是"输出表达式"，把每个 num 放进结果列表：
#   结果按顺序收集：1, 2, 3, 4, 5, 6
#
# 记忆口诀：先外层后内层，谁在 for 前面谁先执行
# 等价于：
# flat = []
# for row in matrix:
#     for num in row:
#         flat.append(num)

# 双重循环生成组合
pairs = [(x, y) for x in range(3) for y in range(3)]
# [(0,0),(0,1),(0,2),(1,0),(1,1),(1,2),(2,0),(2,1),(2,2)]

# 嵌套 + 条件
nums = [(x, y) for x in range(4) for y in range(4) if x != y]
# 排除 x==y 的组合


# ============================================================
# 六、推导式进阶：条件表达式（三元）
# ============================================================
# 推导式里的 if 有两种位置，作用完全不同！

# 位置 1：if 在最后 → 过滤（决定要不要）
[x for x in range(10) if x % 2 == 0]          # [0, 2, 4, 6, 8]

# 位置 2：if/else 在最前 → 选值（决定值是什么）
["偶" if x % 2 == 0 else "奇" for x in range(5)]
# ["偶", "奇", "偶", "奇", "偶"]

# 两个同时用
[x if x > 3 else -x for x in range(6) if x != 0]
# 先过滤 x != 0，再决定值是 x 还是 -x


