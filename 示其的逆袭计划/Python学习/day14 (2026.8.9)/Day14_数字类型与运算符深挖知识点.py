# 六、逻辑运算：and / or / not
# ============================================================
# and：两边都为真才为真
# or ：一边为真就为真
# not：取反

# 短路求值：
#   and 左边为假，右边就不执行
#   or  左边为真，右边就不执行
def never_called():
    print("这行不会执行")
    return True

print(0 and never_called())      # 0，右边根本没执行
print(1 or never_called())       # 1，右边根本没执行

# and / or 返回的不是 True/False，而是"参与运算的对象"
#   1 and 3    → 3
#   0 and 3    → 0
#   1 or 3     → 1
#   0 or "游客" → "游客"
# 常用写法：
#   name = user.get("name") or "游客"

# 真值表（重要）：
#   假：0、0.0、""、[]、()、{}、set()、None
#   真：其他所有值
# 所以 if 判断可以直接写 if data:，不用 if len(data) > 0:


