# 四、位运算（重点）
# ============================================================
# 位运算是直接对二进制位做运算，刷题和 408 都会用到。

# 【补充】什么叫"位"？
#   位（bit）= 二进制的一位，是计算机里最小的信息单位
#   一位只能放两种状态：0 或 1（像开关只有开/关，灯只有亮/灭）
#   十进制每一位能放 0~9；二进制每一位只能放 0 或 1
#   5 写成二进制是 101，意思是：
#     从右往左数：第 0 位 = 1（代表 1），第 1 位 = 0（代表 0 个 2），第 2 位 = 1（代表 1 个 4）
#     所以 5 = 1×4 + 0×2 + 1×1
#   8 个位 = 1 个字节（byte），能表示 0~255
#   "位是 1 还是 0" = 这个开关是开还是关；1 表示这一位有值，0 表示没有值

# 【补充】到底什么是"位运算"？
#   1. 先把数字翻译成二进制（如 5 -> 101）
#   2. 一位一位按规则做逻辑判断
#   3. 把结果拼回十进制
#   可以类比成一排开关：1 = 开，0 = 关
#     & 与   两个开关都开，灯才亮（两个位都是 1 才是 1）
#     | 或   只要有一个开关开，灯就亮（有一个 1 就是 1）
#     ^ 异或 两个开关状态不一样才亮（一个 0 一个 1 才是 1）
#     ~ 取反 把每个开关状态反过来
#     << 左移 整排开关往左挪几位，相当于乘 2 的 n 次方
#     >> 右移 整排开关往右挪几位，相当于整除 2 的 n 次方

# &   按位与：两个位都是 1 才是 1
print("5 & 3 =", 5 & 3)          # 101 & 011 = 001 = 1

# 【补充】怎么判断每一位是 1 还是 0？以 5 & 3 为例：
#   第 1 步：把两个数都展开成二进制，按位对齐
#     5 = 1 0 1
#     3 = 0 1 1
#   第 2 步：从右往左逐列判断，& 的规则是"两个都是 1 结果才是 1"
#     第 0 列：1 & 1 = 1   （两个都是 1 → 结果 1）
#     第 1 列：0 & 1 = 0   （5 这一位是 0 → 结果 0）
#     第 2 列：1 & 0 = 0   （3 这一位是 0 → 结果 0）
#   第 3 步：把每列结果拼起来，得到 001，也就是十进制的 1
#   "位是 1 还是 0" 看的是这一列开关状态：1 表示开、有值，0 表示关、没值

# |   按位或：有一个是 1 就是 1
print("5 | 3 =", 5 | 3)          # 101 | 011 = 111 = 7

# 【补充】5 | 3 的逐位流程：
#   5 = 1 0 1
#   3 = 0 1 1
#   | 的规则：只要有一个 1，结果就是 1
#     第 0 列：1 | 1 = 1
#     第 1 列：0 | 1 = 1
#     第 2 列：1 | 0 = 1
#   结果 111 = 7

# ^   按位异或：相同为 0，不同为 1
print("5 ^ 3 =", 5 ^ 3)          # 101 ^ 011 = 110 = 6

# 【补充】5 ^ 3 的逐位流程：
#   5 = 1 0 1
#   3 = 0 1 1
#   ^ 的规则：两个位不一样，结果才是 1
#     第 0 列：1 ^ 1 = 0   （相同 → 0）
#     第 1 列：0 ^ 1 = 1   （不同 → 1）
#     第 2 列：1 ^ 0 = 1   （不同 → 1）
#   结果 110 = 6

# ~   按位取反（补码表示）
print("~5 =", ~5)                # -6

# 【补充】~5 的流程：
#   Python 中取反的规则：~x = -x - 1
#   所以 ~5 = -5 - 1 = -6
#   位视角：把每一位都反过来（0 变 1、1 变 0）
#     5 写成 8 位是 0000 0101
#     取反后是 1111 1010
#     这个二进制按"补码"规则读，就是 -6
#   现阶段记住公式 ~x = -x - 1 就够用

# <<  左移：相当于乘 2 的 n 次方
print("1 << 3 =", 1 << 3)        # 8

# 【补充】1 << 3 的流程：
#   1 的二进制是 1
#   左移 3 位：整排开关往左挪 3 格，右边补 0
#     1 → 1000
#   1000 = 8 = 1 × 2³
#   结论：a << n 等于 a × 2 的 n 次方

# >>  右移：相当于整除 2 的 n 次方
print("8 >> 2 =", 8 >> 2)        # 2

# 【补充】8 >> 2 的流程：
#   8 的二进制是 1000
#   右移 2 位：整排开关往右挪 2 格，最右边 2 格丢弃
#     1000 → 0010
#   0010 = 2 = 8 整除 2²
#   结论：a >> n 等于 a 整除 2 的 n 次方（向下取整）

# 实用套路：
#   判断奇偶：x & 1 == 0 是偶数，x & 1 == 1 是奇数
#   判断 2 的幂：n > 0 and n & (n - 1) == 0
#   异或找唯一数：a ^ b ^ b = a（同一个数异或两次会抵消）
#   权限标志位：读 = 1 << 0，写 = 1 << 1，执行 = 1 << 2

# 【补充】套路 1：x & 1 判断奇偶
#   原因：二进制最低位只代表 1，其他位都代表 2 的倍数
#     奇数的最低位一定是 1（如 5 = 101）
#     偶数的最低位一定是 0（如 6 = 110）
#   流程：
#     5 & 1：101 & 001 = 001 = 1  → 奇数
#     6 & 1：110 & 001 = 000 = 0  → 偶数
#   x & 1 只关心最低位，其他位都被 1 的 0 抹掉

# 【补充】套路 2：n & (n - 1) == 0 判断 2 的幂
#   原因：2 的幂在二进制里只有一个 1（1、10、100、1000...）
#   n - 1 会把那个唯一的 1 变成 0，并把后面的位全变成 1
#   流程（n = 8）：
#     8  = 1000
#     7  = 0111
#     8 & 7 = 0000 = 0  → 是 2 的幂
#   流程（n = 10）：
#     10 = 1010
#     9  = 1001
#     10 & 9 = 1000 = 8 ≠ 0  → 不是 2 的幂
#   最前面还要 n > 0，因为 0 和负数不是 2 的幂

# 【补充】套路 3：异或找只出现一次的数
#   两条性质：
#     x ^ x = 0   同一个数异或两次会抵消
#     x ^ 0 = x   和 0 异或还是它自己
#   流程（nums = [4, 1, 2, 1, 2]）：
#     4 ^ 1 ^ 2 ^ 1 ^ 2
#     = 4 ^ (1 ^ 1) ^ (2 ^ 2)   成对的先抵消
#     = 4 ^ 0 ^ 0
#     = 4
#   逐位看也行：把所有数按位对齐逐列异或，每个列里出现两次的 1 都会变回 0

# 【补充】套路 4：权限标志位
#   把每种权限想成一排开关里的一个：
#     读 = 1 << 0 = 001
#     写 = 1 << 1 = 010
#     执行 = 1 << 2 = 100
#   组合权限用 |：读写 = 001 | 010 = 011
#   判断权限用 &：011 & 010 = 010 ≠ 0 → 有写权限
#   判断有没有某个权限，看对应开关是不是 1


