# == 与 is 的区别（重要）
# ==  比内容：两个列表内容相同就是 True
# is   比身份：是不是同一个对象（同一块内存）
a = [1, 2]
b = [1, 2]
print("a == b:", a == b)         # True   内容一样
print("a is b:", a is b)         # False  是两个不同的列表

# 小整数缓存：
