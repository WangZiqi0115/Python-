# 复习 Day 19:装饰器 = "给函数套一层外壳",@ 是语法糖,func.__name__ 会被套壳覆盖。
import functools

def log(func):
    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        print(f"开始调用 {func.__name__}")
        result = func(*args, **kwargs)
        print(f"调用结束,结果 {result}")
        return result
    return wrapper

@log
def add(a, b):
    return a + b

print(add(1, 2))
