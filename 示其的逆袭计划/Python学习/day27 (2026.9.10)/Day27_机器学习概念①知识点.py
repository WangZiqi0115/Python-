import numpy as np

# ============================================================
# 一、机器学习在干什么(和传统编程对比)
# ============================================================
# 传统编程: 人写规则 → 电脑照着做
#   比如"判断一个数是奇数还是偶数":人写 if n % 2 == 1,电脑执行。
#
# 机器学习: 人给【例子】→ 电脑自己找规则
#   比如"认出手写数字":你说不清"3 长什么样"的规则(每个人的 3 都不一样),
#   于是给电脑看几万张"图 + 正确答案",让它自己总结出规律。
#
# 类比: 教小孩认数字,你不会给他讲规则,而是指着一堆卡片说
#       "这是 3,这也是 3,这是 7..." 看多了他就会了。机器学习就这么回事。
#   区别: 小孩看几十张,机器要看几万张 —— 机器不聪明,但它算得快、不嫌烦。

# ============================================================
# 二、三种学习方式(先认个脸,我们只用第一种)
# ============================================================
# ★ 监督学习(Supervised): 【有答案】的学习
#   给电脑的每张图都附带正确答案(标签),让它学会"看图 → 说答案"。
#   → 我们的 MNIST 就是这一类!
#
# ★ 无监督学习(Unsupervised): 【没答案】,让电脑自己找结构
#   比如把 10000 张图按"长得像"自动分成几堆(聚类),但没人告诉它每堆是什么。
#
# ★ 强化学习(Reinforcement): 【试错 + 奖励】
#   像训练小狗:做对了给奖励,做错了没奖励,慢慢学会怎么做最好。
#   典型场景: 下棋、打游戏、机器人走路。
#
# 一句话: 我们做的"手写数字识别" = 监督学习 里的【分类】问题。
#   (分类 = 答案是一个"类别";MNIST 有 0~9 共 10 个类别)

# ============================================================
# 三、术语四件套:样本 / 特征 / 标签 / 类别(全用 MNIST 具体化)
# ============================================================
# ★ 样本(sample): 一个"东西"。MNIST 里 = 一张手写数字图。
# ★ 特征(feature): 描述样本的那堆数字 = 输入。MNIST 里 = 784 个像素值。
# ★ 标签(label): 这个样本的正确答案 = 输出。MNIST 里 = 0~9 中的一个数。
# ★ 类别(class): 标签所有可能的取值。MNIST 里 = 0、1、2、…、9 共 10 类。
#
# 命名习惯(以后看论文/代码都这样):
#   X(大写) = 全部样本的特征,是【二维】的 (样本数, 特征数)
#   y(小写) = 全部样本的标签,是【一维】的 (样本数,)
#   记住这条: X 的行数 必须 = y 的长度,一个样本一份答案,不能对不上。
print("\n--- 一个'玩具'数据集(数字小,方便看清结构) ---")
# ★ 示例数据(先看清它长什么样):
#   X 有 6 行 = 6 个样本;每行 4 个数 = 每个样本 4 个特征(假装是 4 个像素)
#   y 有 6 个数 = 6 个样本各自的标签(假装只有 0、1 两类)
X = np.array([[10., 20., 30., 40.],   # 样本0 的 4 个特征
              [50., 60., 70., 80.],   # 样本1
              [90., 10., 20., 30.],   # 样本2
              [40., 50., 60., 70.],   # 样本3
              [20., 30., 40., 50.],   # 样本4
              [80., 70., 60., 50.]])  # 样本5
y = np.array([0, 1, 0, 1, 0, 1])      # 6 个样本的标签(答案)
print("X(特征):\n", X)                 # (6, 4)
print("y(标签):", y)                   # (6,)
print("X 形状:", X.shape)              # (6, 4) → 6 个样本,每个 4 个特征
print("y 形状:", y.shape)              # (6,)   → 6 个样本,一人一个答案
print("样本数一致吗?", X.shape[0] == len(y))   # True ← 这条必须永远成立
print("第0个样本的特征:", X[0], " 它的标签:", y[0])
# 【怎么读】X[0] 是"第0张图的像素",y[0] 是"第0张图的答案"。
#   取样本用 X[0]、取它的答案用 y[0] —— 下标要对上,这就是"一个样本一份答案"。

# ============================================================
# 四、训练集 / 验证集 / 测试集(今天最重要的一节)
# ============================================================
# 【为什么不能拿所有数据来学】
#   想象考试:如果老师提前把考卷原题给你,你背下答案考 100 分,
#   但这不代表你真会 —— 换一张新卷子你就露馅了。
#   模型也一样:如果它"考试考的就是它练过的题",分数虚高,毫无意义。
#
# 所以数据要分成几份,各干各的活:
#   ★ 训练集(train): 用来【学】。模型从这里总结规律(调权重)。
#   ★ 验证集(valid): 用来【挑】。调超参数(如学习率)时看它,避免调歪。
#   ★ 测试集(test):  用来【考】。最后只考一次,成绩才是真实水平。
#   (初学阶段我们先把 train / test 两份搞清楚,验证集 Day 28 之后再细说)
#
# MNIST 官方的分法(记这两个数字):
#   X(60000, 784) + y(60000,) → 训练用
#   X(10000, 784) + y(10000,) → 测试用(官方切好的,不许偷看)
print("\n--- 划分训练集/测试集(8:2) ---")
np.random.seed(0)                     # 固定随机种子 → 每次划分结果一样(Day 26 学过)
n = X.shape[0]                        # 一共 6 个样本
idx = np.random.permutation(n)        # 洗牌:得到乱序下标 [5 2 1 3 0 4]
cut = int(n * 0.8)                    # 前 80% 当训练集 → 切点 = int(4.8) = 4
train_idx, test_idx = idx[:cut], idx[cut:]      # 切片取出两份下标
X_train, y_train = X[train_idx], y[train_idx]   # 特征和标签【用同一份下标】!
X_test, y_test = X[test_idx], y[test_idx]
print("洗牌下标:", idx)
print("训练下标:", train_idx, " 测试下标:", test_idx)
print("训练集 X:", X_train.shape, " 训练集 y:", y_train.shape)   # (4,4) 和 (4,)
print("测试集 X:", X_test.shape, " 测试集 y:", y_test.shape)     # (2,4) 和 (2,)
print("训练集标签:", y_train)
print("测试集标签:", y_test)
# ★ 最后检查一遍:两份下标合起来,是不是正好覆盖 0~5、且不重不漏?
total = set(train_idx.tolist()) | set(test_idx.tolist())    # 集合并集(Day 4 学过)
print("有没有重叠/遗漏?", len(total) == n, " 合起来:", sorted(total))   # True [0..5]
# 【怎么读】"8:2 划分"就是:洗完牌,前 80% 下标给训练,后 20% 给测试。
#   关键点(极易错): X 和 y 必须用【同一份打乱后的下标】去切,
#   否则"图"和"答案"就对不上号了 —— 相当于把甲的答案发给乙。

print("\n--- 换成 MNIST 的规模算一下 ---")
n_mnist = 60000
print("60000 张按 8:2 分:", int(n_mnist * 0.8), "训练 /", n_mnist - int(n_mnist * 0.8))
# → 48000 训练 / 12000 测试(官方其实直接给了 60000/10000,两种都常见)

# ============================================================
# 五、怎么判断模型好不好:准确率 accuracy
# ============================================================
# 分类问题最直观的分数: 猜对了多少个 ÷ 一共多少个。
#   accuracy = (预测 == 真实) 的个数 / 总数
# 记法: True 当 1、False 当 0,求平均 = "True 占的比例" —— 正好就是准确率!
#   所以写法就是: (预测 == 真实).mean()
print("\n--- 算准确率 ---")
y_true = np.array([3, 1, 4, 1, 5])          # 5 个样本的真实标签
pred_zero = np.zeros(5, dtype=int)          # 模型A: 最笨的模型,不管输入都猜 0
pred_rand = np.array([3, 0, 4, 2, 5])       # 模型B: 稍微像样的预测
print("真实标签:", y_true)
print("全猜0的预测:", pred_zero, " 猜对几个:", (pred_zero == y_true).sum())
print("全猜0的准确率:", (pred_zero == y_true).mean())     # 0.0
print("随便猜的预测:", pred_rand, " 猜对几个:", (pred_rand == y_true).sum())
print("随便猜的准确率:", (pred_rand == y_true).mean())    # 0.6
# 【怎么读】(预测 == 真实) 会得到一个 True/False 的数组,
#   对它 .sum() 就是"猜对的个数",.mean() 就是"猜对的比例"(= 准确率)。
#
# ★ 基准(baseline) 的意思:先知道"不动脑子能拿多少分"
#   MNIST 有 10 类 → 瞎猜的期望准确率约 10%(1/10);
#   全猜同一个数字,大概也是 10% 上下。
#   所以以后你的模型要跟 10% 比,而不是跟 0 比;跑到 90%+ 才算真本事。

# ============================================================
# 六、开工前先"体检"数据:标签分布
# ============================================================
# 模型学不好,很多时候不是模型的问题,而是数据有问题。
# 最常看的一项: 每类样本各有多少个(均衡不均衡)。
# 参数顺序标注(新函数):
#   np.unique(①数组, ②return_counts=False)
#     → ① 去重后的值(有哪些不同的标签)
#     → ② 若写 return_counts=True,还会返回每个值出现的次数
# 【怎么读】np.unique(数组, return_counts=True) = "里面有哪些不同的值,各出现几次"。
print("\n--- 检查标签分布 ---")
y_like = np.array([0, 1, 1, 2, 0, 3, 0, 1])
vals, counts = np.unique(y_like, return_counts=True)   # 一次拿两个结果(元组解包,Day 16 学过)
print("标签样本:", y_like)
print("有哪些标签:", vals)              # [0 1 2 3]
print("各自出现次数:", counts)          # [3 3 1 1]  ← 0和1各3个,2和3各1个
# 【怎么读】vals 和 counts 是一一对应的: vals[0]=0 出现 counts[0]=3 次。
#   如果某一类特别少(比如 2 只有 1 个),模型就容易"没见过、学不会"这类。

# ============================================================
# 七、批 batch / 轮 epoch(为 Day 30、Day 34 铺路)
# ============================================================
# 训练时不会"60000 张一次性塞进去",而是一小批一小批地喂:
#   ★ batch(批): 一次喂给模型的样本数,常见 32 / 64 / 100 / 128。
#   ★ epoch(轮): 把整个训练集完整看一遍 = 1 个 epoch。
# 为什么要分批?
#   ① 内存/显存装不下 6 万张图(每张 784 个数);
#   ② 一小批算一次、立刻改进一点,比"全看完再改"学得快。
print("\n--- 分批长什么样 ---")
bs = 8                                       # 每批 8 个
fake = np.arange(20).reshape(20, 1)          # 假装有 20 个样本
print("20 个样本,每批 8 个:")
print("第0批:", fake[0:bs].ravel())           # 用切片取第 0 批
print("第1批:", fake[bs:2 * bs].ravel())
print("第2批:", fake[2 * bs:3 * bs].ravel())  # 最后一批只剩 4 个(20 = 8+8+4)
print("多少批:", 20 // bs, "(余", 20 % bs, "个)")   # 2 批整 + 余 4 个
print("MNIST 60000 张,每批 100:", 60000 // 100, "批")   # 600 批 = 1 个 epoch
# 【怎么读】取第 k 批 = 切片 data[k*批大小 : (k+1)*批大小]。

