# 陷阱 3:矩阵乘法不可交换
#   A @ B ≠ B @ A(通常)。顺序千万别反,反了要么报错要么结果完全不同。
#   【怎么读】神经网络里固定是"权重 @ 输入",顺序错了整个网络就乱套。
#
# 陷阱 4:一维数组的"奇怪行为"
#   x.shape = (784,) 是一维。W(64,784) @ x → 得到 (64,) 一维。
#   想要 (64,1) 这种"列向量"形状,得写 x.reshape(784, 1)。
#   一维数组参与矩阵乘,结果常常也是"少了一维",新手容易懵。
#
# 陷阱 5:忘记 .T 导致维度对不上
#   数据是 (100, 784) 但要和 (64, 784) 乘 → 公共维度数 784≠64 → 报错
#   这时用 W.T 把 (64,784) 转成 (784,64) 就能乘。
#
# 陷阱 6:np.dot 对一维数组会变成"点积"(返回标量,不是矩阵)
#   np.dot(x, y) 当 x,y 都是一维 → 返回一个数(两串数一对一乘完再全加起来),不是矩阵!
#   想做矩阵乘,用 @ 更省心。

