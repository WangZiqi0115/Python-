# ------------------------------------------------------------
# 例题 1:矩阵乘法算形状(先会看维度,才会不报错)
# 思路:记住 (行A×公共维度数) @ (公共维度数×列B) = (行A×列B),公共维度数必须相等
# ------------------------------------------------------------
print("\n--- 例题1: 判断能不能乘 ---")
a1 = np.ones((3, 4))     # 3×4
b1_ = np.ones((4, 5))    # 4×5
c1 = a1 @ b1_            # 公共维度数 4=4 对上了 → (3,5)
print("a1(3×4) @ b1(4×5) =", c1.shape)   # (3,5)
# 关键点: 公共维度数相等(这里是4)才能乘,结果行数=A行数、列数=B列数。

# 反例(会报错):
# wrong = a2 @ b  # 若 A(3,4) @ B(2,5),公共维度数 4≠2 → ValueError
#   ValueError: matmul: Input operand 1 has a mismatch in its core dimension 0
#   → 意思就是"A的列数 ≠ B的行数"。

# ------------------------------------------------------------
# 例题 2:@ 和 * 的区别(最容易翻车)
# 思路:* 是元素对元素,要求形状一样;@ 是矩阵乘,要求公共维度数相等
# ------------------------------------------------------------
m = np.array([[2, 0],
              [0, 2]])
print("\n--- 例题2 ---")
print("m * m(逐元素):\n", m * m)     # 每个元素平方 [[4,0],[0,4]]
print("m @ m(矩阵乘):\n", m @ m)     # 对角阵相乘 [[4,0],[0,4]](这俩例子碰巧一样)
# 换个非对角就看出区别了:
n = np.array([[1, 2],
              [3, 4]])
print("n * n:\n", n * n)     # [[1,4],[9,16]]
print("n @ n:\n", n @ n)     # [[7,10],[15,22]]  ← 和上面完全不同!
# 关键点: 想"两个矩阵做矩阵乘法"就用 @;想"每个元素自己运算"用 *。

# ------------------------------------------------------------
# 例题 3:转置让维度对齐
# 思路:维度对不上时,用 .T 翻一面
# ------------------------------------------------------------
print("\n--- 例题3 ---")
X = np.random.rand(100, 784)   # 100张图,每张784像素,横着排
W = np.random.rand(784, 64)    # 权重:784输入 → 64输出
# X(100,784) @ W(784,64) → 公共维度数784对上了 → (100,64),不用转置
out = X @ W
print("X(100×784) @ W(784×64) =", out.shape)   # (100, 64)
W2_ = np.random.rand(64, 10)   # 想再来一步 64→10
out2 = out @ W2_               # (100,64) @ (64,10) → (100,10)
print("再 @ W2(64×10) =", out2.shape)          # (100,10)
# 关键点: 只要"公共维度数总是相等",就能一路乘下去;有时数据方向不对,就 .T 转一下。

# ------------------------------------------------------------
# 例题 4:最小网络,手把手算一遍前向传播(核心例题)
# 思路:用 3 → 2 → 1 的最小网络,自己验证每一步的数值
# ------------------------------------------------------------
print("\n--- 例题4: 最小网络前向传播,手算验证 ---")
x = np.array([2.0, 3.0, -1.0])          # 3个输入
W1 = np.array([[1.0, 2.0, -1.0],
               [0.0, 1.0,  1.0]])       # 2个神经元 × 3个输入
b1 = np.array([0.5, -0.5])
W2 = np.array([[1.0, -1.0]])            # 1个输出 × 2个神经元
b2 = np.array([0.0])

z1 = W1 @ x + b1
h1 = np.maximum(0, z1)                  # 激活: 负数归0
z2 = W2 @ h1 + b2

print("输入 x:", x)
print("z1 = W1@x+b1 =", z1)
# 手算: z1[0]=1*2+2*3+(-1)*(-1)+0.5 = 9.5
#       z1[1]=0*2+1*3+1*(-1)+(-0.5) = 1.5  → 输出 [9.5 1.5] ✓
print("h1 = 激活后 =", h1)              # [9.5 1.5]  都是正数,没变
print("z2 = W2@h1+b2 =", z2)
# 手算: 1*9.5 + (-1)*1.5 + 0 = 8.0  → 输出 [8.] ✓
# 关键点: 这个小网络和你真正的 784→64→10 是同一回事,只是数字小了。
#        换个"全是正输入"的例子,就能看到激活把负数抹0的效果。
x2 = np.array([1.0, -10.0, 0.0])        # 换个输入: 中间那个像素很"暗"(负数)
z1b = W1 @ x2 + b1
print("\n换个输入 x2:", x2)
print("z1b(激活前):", z1b)             # 会出现负数
print("h1b(激活后):", np.maximum(0, z1b))  # 负的变0了,正的保留
# 手算: z1b[0]=1*1+2*(-10)+(-1)*0+0.5 = -18.5 → 激活后 0
#       z1b[1]=0*1+1*(-10)+1*0+(-0.5) = -10.5 → 激活后 0
# 关键点: 权重有正有负,加权求和后得分可能为负 → 激活把负的归0,只留"亮"的。

# ============================================================
# 七、常见陷阱
# ============================================================
# 陷阱 1:公共维度数不匹配 → 报错
#   (3,4) @ (2,5)  → 公共维度数 4≠2 → ValueError
#   报错信息: ...mismatch in its core dimension 0...  意思是"A列数≠B行数"
#
# 陷阱 2:把 * 当成矩阵乘
#   np.array([[1,2],[3,4]]) * 它自己 → 逐元素平方,不是矩阵乘!
#   想做矩阵乘 → 用 @。
