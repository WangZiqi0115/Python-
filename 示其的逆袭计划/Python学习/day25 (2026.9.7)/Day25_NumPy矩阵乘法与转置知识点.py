import numpy as np

# ============================================================
# 一、先复习: 一个"图"在 NumPy 里到底是什么
# ============================================================
# 昨天说 MNIST 每张图是 28x28,拉平是 784 个数字。
# 今天起你把它看成"一个向量 x":784 个数排成一长串。
# 神经网络要做的: 把 784 个输入,算成 10 个输出(0~9 各一个概率)。
#
# 这个"从一堆数算出另一堆数"的过程,就是矩阵乘法。
print("\n--- 一个输入向量 ---")
x = np.random.rand(784)        # 模拟一张图的784个像素(0~1)
print("x 的形状:", x.shape)    # (784,)  一维向量,784个数

# ============================================================
# 二、矩阵乘法 @  和  np.dot  (核心!重点)
# ============================================================
# 先搞懂 A 和 B 是什么。我们直接从"最小的例子"开始,自己动手算一遍就懂了。
print("\n--- 矩阵乘法 ---")
# ★ A 和 B 是什么? (示例数据,先看清它们再往下)
#   A(2行3列) = 2 个"东西",每个东西有 3 个属性
#   B(3行2列) = 3 个"东西",每个东西有 2 个属性
A = np.array([[1, 2, 3],        # ← A 的第 0 行: 一个东西,3个属性 1、2、3
              [4, 5, 6]])        # ← A 的第 1 行: 另一个东西,属性 4、5、6
B = np.array([[7, 8],            # ← B 的第 0 行: 3 个东西里的第1个,2个属性
              [9, 10],           # ← B 的第 1 行
              [11, 12]])         # ← B 的第 2 行
print("A =", A, "  形状", A.shape)   # (2,3)
print("B =", B, "\n形状", B.shape)    # (3,2)

# ★ A @ B 做了什么运算? (矩阵乘法的"动作")
#   拿 A 的【每一行】,去碰 B 的【每一列】,一对一相乘,再把它们全加起来 → 填一个新格子。
#   A 的第 0 行 [1,2,3] × B 的第 0 列 [7,9,11]:
#     结果 (0,0) = 1*7 + 2*9 + 3*11 = 7 + 18 + 33 = 58
#   A 的第 0 行 [1,2,3] × B 的第 1 列 [8,10,12]:
#     结果 (0,1) = 1*8 + 2*10 + 3*12 = 8 + 20 + 36 = 64
#   A 的第 1 行 [4,5,6] × B 的第 0 列 [7,9,11]:
#     结果 (1,0) = 4*7 + 5*9 + 6*11 = 139
#   A 的第 1 行 [4,5,6] × B 的第 1 列 [8,10,12]:
#     结果 (1,1) = 4*8 + 5*10 + 6*12 = 154
#   所以 结果 C = [[ 58  64],
#               [139 154]]   ← 2行2列
print("A(2×3) @ B(3×2):")
print(A @ B)                        # (2,2)  公共维度数 3 对上了
# 手算对上了: (0,0)=58、(0,1)=64、(1,0)=139、(1,1)=154

# ★ 为什么能这样乘? (关键规则,务必记牢)
#   两个矩阵要能相乘,【A 的列数必须等于 B 的行数】。
#   这里 A 有 3 列、B 有 3 行 → 3=3,刚好能乘。
#   这个"两边都出现的 3"叫【公共维度数】= A的列数 = B的行数。
#   对不上(比如 A 是3列、B 是5行)就是最常见的乘法报错。
#   【怎么读】A 的列数"伸进"B 的行数,两个必须一样大,否则无法"配对相乘"。

# 参数顺序标注(新函数):
#   np.dot(①数组A, ②数组B)   → A 和 B 做矩阵乘法
# @  是运算符,写法更简洁:     A @ B
# 【怎么读】A @ B = "A 的每一行,去乘 B 的每一列,乘完相加,填出一张新表"。
# (2,3)@(3,2) → (2,2):
#  第0行×第0列 = 1*7+2*9+3*11 = 58   ← 上面手算过,对上了
#  第0行×第1列 = 1*8+2*10+3*12 = 64
#  第1行×第0列 = 4*7+5*9+6*11 = 139
#  第1行×第1列 = 4*8+5*10+6*12 = 154
# 结果: [[ 58  64],
#       [139 154]]

print("结果形状:", (A @ B).shape)     # (2, 2)  行数取自A、列数取自B

# np.dot 和 @ 效果一样(二维时):
print("\nnp.dot(A, B):")
print(np.dot(A, B))
# 提醒: 以后深度学习代码里基本都用 @,因为它最直观、最常用。

# ★ 三个数字帮你记结果形状:
#   结果的行数 = A 的行数; 结果的列数 = B 的列数。
#   换句话说: (A的行 × A的列) @ (B的行 × B的列) =
#             (A的行 × B的列),前提是 A的列 = B的行。

# ============================================================
# 三、矩阵乘法 @  与  逐元素乘法 *  别搞混! (重点)
# ============================================================
# 这是新手最大的坑:
#   *  → 逐元素相乘(哈达玛积,元素对元素),要求形状【一模一样】
#   @  → 矩阵乘法(行乘列再相加),要求"A的列数 = B的行数"
print("\n--- @ 和 * 的区别 ---")
M = np.array([[1, 2],
              [3, 4]])
print("M:\n", M)
print("M * M(逐元素):\n", M * M)    # 每个元素自己乘自己
# [[ 1  4]
#  [ 9 16]]
print("M @ M(矩阵乘):\n", M @ M)     # 真正的矩阵乘法
# [[ 7 10]
#  [15 22]]
# (0,0) = 1*1+2*3 = 7 → 和逐元素完全不一样!
# 【怎么读】* 是"一对一相乘",@ 是"整行整列地乘加"。看你要哪个。

# ============================================================
# 四、转置 .T  (把行列互换)
# ============================================================
# 转置 = 把矩阵"沿着对角线翻个身": 行变列,列变行。
# (2,3) 转置后变成 (3,2)。
# 用法: 数组.T,是属性,不用加括号。
# 【怎么读】A.T = "把 A 的行和列对调"。
print("\n--- 转置 ---")
A = np.array([[1, 2, 3],
              [4, 5, 6]])            # (2,3)
print("A:\n", A)
print("A.T(转置):\n", A.T)          # (3,2)
# [[ 1  4]
#  [ 2  5]
#  [ 3  6]]

# ★ 为什么 MNIST 有用: 让维度"对得上"
#   W1 是 (64, 784),x 是 (784,)。要想 W1 @ x,公共维度数 784 对 784,正好。
#   但有时候数据是"横着"的,就要用 .T 转一下,让公共维度数对齐。
#   比如某个数组是 (100, 784)(100张图),想和 W1 乘:
#     (100, 784) @ (784, 64) → 用 W1.T 把 (64,784) 转成 (784,64)
#   转置就是"维度不对时,翻个面去对齐"的万能钥匙。

# ============================================================
# 五、★ 神经网络的心脏: 前向传播(Forward Pass)
# ============================================================
# 前面几节你可能已经有点晕了。别急,这一节我只用【极小的数字】,
# 让你亲手算一遍,你就能彻底明白"神经网络到底在干嘛"。
#
# 先忘掉 784、64、10 那些大数字。我们做一个"最小版"网络:
#   输入 = 3 个数(假装一张只有3个像素的"小图")
#   中间 = 2 个神经元
#   输出 = 1 个得分
# 等你看懂这个小网络,再把 3 换成 784、2 换成 64、1 换成 10,就一样了。

# ---------------- 第 0 步: 输入 ----------------
x = np.array([2.0, 3.0, -1.0])     # 一张"小图"的3个像素(有正有负,方便演示)
print("输入 x:", x, " 形状:", x.shape)   # (3,)

# ---------------- 第 1 步: x 变成 2 个神经元 ----------------
# 权重 W1 的每一行,是一个神经元的"对待每个输入的态度":
#   第0个神经元: 看第0个像素时×1、第1个像素×2、第2个像素×-1
#   第1个神经元: 看第0个像素时×0、第1个像素×1、第2个像素×1
# 【怎么读】W1 是 "2行3列": 2个神经元,每个要处理3个输入。
#          一个神经元把3个输入"加权求和" → 得到一个数(它的"得分")。
W1 = np.array([[1.0, 2.0, -1.0],
               [0.0, 1.0,  1.0]])      # (2,3)  2个神经元 × 3个输入
b1 = np.array([0.5, -0.5])             # 每个神经元自带一个"偏置",相当于给它加个底分

# 一个神经元的分 = (它的权重 和 3个输入 一对一乘,再加起来) + 偏置
# 手算验证第0个神经元:
#   1.0*2 + 2.0*3 + (-1.0)*(-1) = 2 + 6 + 1 = 9,再加偏置 0.5 → 9.5
z1 = W1 @ x + b1
print("\n第1步 W1 @ x + b1 =", z1, " 形状:", z1.shape)   # (2,)  就是9.5和2.5,看下面
# (2,3)@(3,)+...  → 公共维度数 3 对上了 → 得到 2 个数。
# 手算: z1[0]=1*2+2*3+(-1)*(-1)+0.5 = 9.5
#       z1[1]=0*2+1*3+1*(-1)+(-0.5) = 1.5

# ---------------- 第 2 步: 激活(先扫一眼,只是把负的抹平,不深究) ----------------
# 现实中神经元的"得分"不能是负数,会把负的去掉。这叫激活函数 ReLU。
# np.maximum(0, z) 的意思: z里的数,小于0的都变成0,大于0的保留。
h1 = np.maximum(0, z1)
print("第2步 激活后 h1 =", h1)                    # [9.5, 1.5]  —— 都是正数,没变化
# 【怎么读】np.maximum(0, z) = "把 z 和 0 一一比较,取更大的那个" → 负的归0。

# ---------------- 第 3 步: 2个神经元 → 1个输出 ----------------
W2 = np.array([[1.0, -1.0]])            # (1,2)  1个输出 × 2个神经元
b2 = np.array([0.0])
z2 = W2 @ h1 + b2
print("第3步 W2 @ h1 + b2 =", z2, " 形状:", z2.shape)   # (1,)  一个得分
# 手算: 1*9.5 + (-1)*1.5 + 0 = 8.0
# (1,2)@(2,) → 公共维度数 2 对上了 → 得到 1 个数。

print("\n---------- 回到真实尺寸 784 → 64 → 10 ----------")
# 上面的小网络是"3 → 2 → 1",你的网络是"784 → 64 → 10"。
# 形状完全一样,只是数字大了:
#   输入 x:   (3,)  变成了 (784,)    —— 一张图拉平成784个数
#   W1:       (2,3) 变成了 (64,784)  —— 64个神经元 × 784个输入
#   b1:       (2,)  变成了 (64,)
#   h1(中间): (2,)  变成了 (64,)     —— 也就是"64个隐藏神经元"
#   W2:       (1,2) 变成了 (10,64)   —— 10个输出类别 × 64个神经元
#   z2(输出): (1,)  变成了 (10,)     —— 0~9 各一个得分
# 所以"前向传播"从头到尾就是两步 W @ x + b(中间夹一次激活)。
# 你今天只要看懂这两个形状怎么"对得上",就算过关了。

# 快速验证真实尺寸的形状能不能走通(先不细看每个数,只看形状):
np.random.seed(0)                # 固定随机数,每次结果一样,方便你对照
# 真实尺寸的网络,权重是随机初始化的(还没训练,猜对纯靠运气):
W1 = np.random.randn(64, 784)    # (64,784)
b1 = np.random.randn(64)         # (64,)
x = np.random.rand(784)          # 一张图,784个像素 (0~1)

print("\n--- 真实尺寸 第1步: 784 → 64 ---")
z1 = W1 @ x + b1                 # (64,784)@(784,) → (64,)
print("z1 形状:", z1.shape)       # (64,)  64个神经元各自的得分
h1 = np.maximum(0, z1)           # 激活,负数归0
print("h1(激活后)形状:", h1.shape) # (64,)

print("\n--- 真实尺寸 第2步: 64 → 10 ---")
W2 = np.random.randn(10, 64)     # (10,64)
b2 = np.random.randn(10)
z2 = W2 @ h1 + b2                # (10,64)@(64,) → (10,)
print("z2 形状:", z2.shape)       # (10,)  0~9 各一个得分

# 最后一步(今天不深究,知道它把得分变成概率就行):
#   softmax 把 z2 那 10 个得分,归一化成长度10、加起来=1 的概率数组。
#   挑概率最大的那个下标,就是网络"猜"的数字。
e = np.exp(z2 - z2.max())
prob = e / e.sum()
print("10个概率,加起来 =", prob.sum())                  # 约等于 1.0
print("网络猜的是: ", int(np.argmax(prob)), "号")      # 现在没训练,纯随机
# 关键点: 【前向传播 = 2 次 W @ x + b,中间夹一次激活】。
#         前半段都是形状上"对得上"就通了;至于概率/激活怎么细算,后几天讲。
#         你今天的任务是看懂 W1(64,784) 和 x(784,) 怎么"严丝合缝"地乘起来。


