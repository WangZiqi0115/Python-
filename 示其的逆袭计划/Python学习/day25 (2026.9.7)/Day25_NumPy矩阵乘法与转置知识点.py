# ------------------------------------------------------------
# 例题 1:矩阵乘法算形状(先会看维度,才会不报错)
# 思路:记住 (行A×内维) @ (内维×列B) = (行A×列B),内维必须相等
# ------------------------------------------------------------
print("\n--- 例题1: 判断能不能乘 ---")
a1 = np.ones((3, 4))     # 3×4
b1_ = np.ones((4, 5))    # 4×5
c1 = a1 @ b1_            # 内维 4=4 对上了 → (3,5)
print("a1(3×4) @ b1(4×5) =", c1.shape)   # (3,5)
# 关键点: 内维相等(这里是4)才能乘,结果行数=A行数、列数=B列数。

# 反例(会报错):
# wrong = a2 @ b  # 若 A(3,4) @ B(2,5),内维 4≠2 → ValueError
#   ValueError: matmul: Input operand 1 has a mismatch in its core dimension 0
#   → 意思就是"A的列数 ≠ B的行数"。

# ------------------------------------------------------------
# 例题 2:@ 和 * 的区别(最容易翻车)
# 思路:* 是元素对元素,要求形状一样;@ 是矩阵乘,要求内维相等
# ------------------------------------------------------------
m = np.array([[2, 0],
              [0, 2]])
print("\n--- 例题2 ---")
print("m * m(逐元素):\n", m * m)     # 每个元素平方 [[4,0],[0,4]]
print("m @ m(矩阵乘):\n", m @ m)     # 对角阵相乘 [[4,0],[0,4]](这俩例子碰巧一样)
# 换个非对角就看出区别了:
n = np.array([[1, 2],
              [3, 4]])
print("n * n:\n", n * n)     # [[1,4],[9,16]]
print("n @ n:\n", n @ n)     # [[7,10],[15,22]]  ← 和上面完全不同!
# 关键点: 想"两个矩阵做矩阵乘法"就用 @;想"每个元素自己运算"用 *。

# ------------------------------------------------------------
# 例题 3:转置让维度对齐
# 思路:维度对不上时,用 .T 翻一面
# ------------------------------------------------------------
print("\n--- 例题3 ---")
X = np.random.rand(100, 784)   # 100张图,每张784像素,横着排
W = np.random.rand(784, 64)    # 权重:784输入 → 64输出
# X(100,784) @ W(784,64) → 内维784对上了 → (100,64),不用转置
out = X @ W
print("X(100×784) @ W(784×64) =", out.shape)   # (100, 64)
W2_ = np.random.rand(64, 10)   # 想再来一步 64→10
out2 = out @ W2_               # (100,64) @ (64,10) → (100,10)
print("再 @ W2(64×10) =", out2.shape)          # (100,10)
# 关键点: 只要"内维总是相等",就能一路乘下去;有时数据方向不对,就 .T 转一下。

# ------------------------------------------------------------
# 例题 4:把一张图过一遍网络,看它"猜"什么数字(核心例题)
# 思路:用你刚才学的前向传播,随机权重下"猜"一次
# ------------------------------------------------------------
np.random.seed(1)
def forward(x, W1, b1, W2, b2):
    z1 = W1 @ x + b1
    h1 = np.maximum(0, z1)      # ReLU
    z2 = W2 @ h1 + b2
    return z2

W1 = np.random.randn(64, 784)
b1 = np.random.randn(64)
W2 = np.random.randn(10, 64)
b2 = np.random.randn(10)

img = np.random.rand(784)        # 一张随机图(先凑合看)
scores = forward(img, W1, b1, W2, b2)
guess = int(np.argmax(scores))
print(f"\n--- 例题4 ---")
print("这张图被网络猜成:", guess, "号数字")
print("10 个原始得分:", np.round(scores, 2))
# 关键点: 现在权重是随机的,猜对纯靠运气;以后Day 34训练好权重,猜的才准。
#        但"结构"你已经搭起来了——2 次矩阵乘法 + 激活,就是前向传播。
#        这正是你计划里"从零搭网络"的第一个核心零件。

# ============================================================
# 七、常见陷阱
# ============================================================
# 陷阱 1:内维不匹配 → 报错
#   (3,4) @ (2,5)  → 内维 4≠2 → ValueError
#   报错信息: ...mismatch in its core dimension 0...  意思是"A列数≠B行数"
#
# 陷阱 2:把 * 当成矩阵乘
#   np.array([[1,2],[3,4]]) * 它自己 → 逐元素平方,不是矩阵乘!
#   想做矩阵乘 → 用 @。
#
# 陷阱 3:矩阵乘法不可交换
#   A @ B ≠ B @ A(通常)。顺序千万别反,反了要么报错要么结果完全不同。
#   【怎么读】神经网络里固定是"权重 @ 输入",顺序错了整个网络就乱套。
#
# 陷阱 4:一维数组的"奇怪行为"
#   x.shape = (784,) 是一维。W(64,784) @ x → 得到 (64,) 一维。
#   想要 (64,1) 这种"列向量"形状,得写 x.reshape(784, 1)。
#   一维数组参与矩阵乘,结果常常也是"少了一维",新手容易懵。
#
# 陷阱 5:忘记 .T 导致维度对不上
#   数据是 (100, 784) 但要和 (64, 784) 乘 → 内维 784≠64 → 报错
#   这时用 W.T 把 (64,784) 转成 (784,64) 就能乘。
#
# 陷阱 6:np.dot 对一维数组会变成"点积"(返回标量,不是矩阵)
#   np.dot(x, y) 当 x,y 都是一维 → 返回一个数(内积),不是矩阵!
#   想做矩阵乘,用 @ 更省心。

