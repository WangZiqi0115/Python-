# Day 25 · NumPy 矩阵乘法与转置 (2026.9.7)
# ============================================
# 今天我们学的是【整个神经网络的心脏】——矩阵乘法。
# 你回头看 Day 24 那句"每天学的每招都跟 MNIST 有关",今天这招是其中最要紧的。
#
# 一句话: 神经网络的前向传播(Forward Pass),本质上就是一连串【矩阵乘法】。
#   x(输入) --W1--> h1(隐藏层) --W2--> 输出(10个概率)
#   其中 W1、W2 是【权重矩阵】,x 是输入向量,中间全是 @(矩阵乘号)。
#   所以矩阵乘法学不会,后面搭网络就是空中楼阁。
#
# 你已经有的底子(高代里叫"矩阵乘法"):
#   A(行×内维) @ B(内维×列) = C(行×列)
#   高代老师叫它"行乘列再相加";今天只看 NumPy 怎么"一行代码算完"它。
#
# ------------------------------------------------------------------
# 运行前先装库(一次即可):  pip install numpy
# 想动手验证,把代码复制到「代码测试专用.py」里跑。

import numpy as np

# ============================================================
# 一、先复习: 一个"图"在 NumPy 里到底是什么
# ============================================================
# 昨天说 MNIST 每张图是 28x28,拉平是 784 个数字。
# 今天起你把它看成"一个向量 x":784 个数排成一长串。
# 神经网络要做的: 把 784 个输入,算成 10 个输出(0~9 各一个概率)。
#
# 这个"从一堆数算出另一堆数"的过程,就是矩阵乘法。
print("\n--- 一个输入向量 ---")
x = np.random.rand(784)        # 模拟一张图的784个像素(0~1)
print("x 的形状:", x.shape)    # (784,)  一维向量,784个数

# ============================================================
# 二、矩阵乘法 @  和  np.dot  (核心!重点)
# ============================================================
# 高代里: A(m×n) @ B(n×k) = C(m×k)   —— 内维 n 必须相等。
#   C 的第 i 行第 j 列 = A 的第 i 行 与 B 的第 j 列 逐项相乘再相加。
# NumPy 里直接用一个 @ 或 np.dot() 一次算完,不用写循环。
#
# 参数顺序标注(新函数):
#   np.dot(①数组A, ②数组B)   → A 和 B 做矩阵乘法
# @  是运算符,写起来更简洁:   A @ B
# 【怎么读】A @ B = "A 的每一行,和 B 的每一列做内积",得到一个新矩阵。
print("\n--- 矩阵乘法 ---")
A = np.array([[1, 2, 3],
              [4, 5, 6]])            # 2行3列 (2,3)
B = np.array([[7, 8],
              [9, 10],
              [11, 12]])            # 3行2列 (3,2)
print("A(2×3) @ B(3×2):")
print(A @ B)                        # (2,2)  内维3对上了
# (2,3)@(3,2) → (2,2):
#  第0行×第0列 = 1*7+2*9+3*11 = 58
#  第0行×第1列 = 1*8+2*10+3*12 = 64
#  第1行×第0列 = 4*7+5*9+6*11 = 139
#  第1行×第1列 = 4*8+5*10+6*12 = 154
# 结果: [[ 58  64],
#       [139 154]]

print("结果形状:", (A @ B).shape)     # (2, 2)  行数取自A、列数取自B

# np.dot 和 @ 效果一样(二维时):
print("\nnp.dot(A, B):")
print(np.dot(A, B))
# 提醒: 以后深度学习代码里基本都用 @,因为它最直观、最常用。

# ★ 三个数字帮你记形状规则:
#   (行A × 内维) @ (内维 × 列B) = (行A × 列B)
#   关键: ①A的列数(B的行数)必须相等 → 才能乘
#         ②结果的行数 = A的行数,结果列数 = B的列数
#   就像高代: (m×n)乘(n×k)得(m×k)。

# ============================================================
# 三、矩阵乘法 @  与  逐元素乘法 *  别搞混! (重点)
# ============================================================
# 这是新手最大的坑:
#   *  → 逐元素相乘(哈达玛积,元素对元素),要求形状【一模一样】
#   @  → 矩阵乘法(行乘列再相加),要求"A的列数 = B的行数"
print("\n--- @ 和 * 的区别 ---")
M = np.array([[1, 2],
              [3, 4]])
print("M:\n", M)
print("M * M(逐元素):\n", M * M)    # 每个元素自己乘自己
# [[ 1  4]
#  [ 9 16]]
print("M @ M(矩阵乘):\n", M @ M)     # 真正的矩阵乘法
# [[ 7 10]
#  [15 22]]
# (0,0) = 1*1+2*3 = 7 → 和逐元素完全不一样!
# 【怎么读】* 是"一对一相乘",@ 是"整行整列地乘加"。看你要哪个。

# ============================================================
# 四、转置 .T  (把行列互换)
# ============================================================
# 转置 = 把矩阵"沿着对角线翻个身": 行变列,列变行。
# (2,3) 转置后变成 (3,2)。
# 用法: 数组.T,是属性,不用加括号。
# 【怎么读】A.T = "把 A 的行和列对调"。
print("\n--- 转置 ---")
A = np.array([[1, 2, 3],
              [4, 5, 6]])            # (2,3)
print("A:\n", A)
print("A.T(转置):\n", A.T)          # (3,2)
# [[ 1  4]
#  [ 2  5]
#  [ 3  6]]

# ★ 为什么 MNIST 有用: 让维度"对得上"
#   W1 是 (64, 784),x 是 (784,)。要想 W1 @ x,内维 784 对 784,正好。
#   但有时候数据是"横着"的,就要用 .T 转一下,让内维对齐。
#   比如某个数组是 (100, 784)(100张图),想和 W1 乘:
#     (100, 784) @ (784, 64) → 用 W1.T 把 (64,784) 转成 (784,64)
#   转置就是"维度不对时,翻个面去对齐"的万能钥匙。

# ============================================================
# 五、★ 神经网络的心脏: 前向传播(Forward Pass)
# ============================================================
# 现在把前面全串起来。你的网络是 784 → 64 → 10:
#   输入层:784 个数字(一张图)   x: (784,)
#   隐藏层:64 个神经元          W1: (64, 784)   偏置 b1: (64,)
#   输出层:10 个概率(0~9)       W2: (10, 64)    偏置 b2: (10,)
# 前向传播 = 两步矩阵乘法:
#   ① z1 = W1 @ x + b1  →  64 个"得分"
#   ② h1 = ReLU(z1)     →  把负的分抹成0(激活函数,后天才细讲)
#   ③ z2 = W2 @ h1 + b2 →  10 个"得分"(0~9各一个)
#   ④ softmax(z2)       →  10 个概率,加起来=1
#
# 今天你只需看懂①和③: 矩阵乘法把"上一层的数"算成"下一层的数"。
# 这就是整个神经网络在干的事。后面学的激活/softmax/梯度,都是搭在这上面的。

# 先看个小小的全流程(用随机权重,先不训练,只看形状能不能走通):
np.random.seed(0)               # 固定随机数,结果可复现(方便演示)
W1 = np.random.randn(64, 784)   # 64个神经元 × 784个输入  形状(64,784)
b1 = np.random.randn(64)        # 64个偏置
x = np.random.rand(784)         # 一张图,784个像素

print("\n--- 前向传播 第1步: 784 → 64 ---")
z1 = W1 @ x + b1                # (64,784) @ (784,) + (64,) → (64,)
print("z1 形状:", z1.shape)      # (64,)  64个神经元各自的"得分"
# 关键点: W1(64×784) 的"64"是输出神经元个数,"784"是输入维度。
#         和 x(784,) 乘 → 内维 784 对上 → 得到 64 个数。

# 激活(先扫一眼,明天细讲): 把负数抹成0
h1 = np.maximum(0, z1)          # ReLU: 负数→0,正数不变
print("h1(激活后)形状:", h1.shape)   # (64,)

W2 = np.random.randn(10, 64)    # 10个类别 × 64个隐藏神经元
b2 = np.random.randn(10)
z2 = W2 @ h1 + b2               # (10,64) @ (64,) → (10,)
print("\n--- 前向传播 第2步: 64 → 10 ---")
print("z2 形状:", z2.shape)      # (10,)  0~9 各一个原始得分

# 最后 softmax 变成 10 个概率(先留着悬念,今天不细讲)
e = np.exp(z2 - z2.max())       # 减最大值防溢出(细节后补)
prob = e / e.sum()
print("10 个概率,加起来 =", prob.sum())   # 约等于 1.0
print("概率最大的那个类别:", int(np.argmax(prob)))   # 网络"猜"这张图是哪个数字
# 关键点: 整个"猜数字"的过程,就是 2 次矩阵乘法。这就是神经网络的心脏。


