# ============================================================
# 一、四大容器总览（Day 1-4）
# ============================================================
# 列表 []    ：有序、可变、可重复 → 动态数据
# 元组 ()    ：有序、不可变、可重复 → 固定数据
# 字典 {}    ：键值对、可变、key 不重复 → 按名字查找
# 集合 {}    ：无序、可变、元素不重复 → 去重/集合运算
#
# 创建：
#   list / tuple / dict / set
# 转换：
#   list(t) set(d) dict(zip(keys, values))
# 常用操作：
#   增删改查、遍历、推导式、sorted、len、in
# 【补充】怎么查字典里有没有某个键或值？
#   查键：键 in 字典（"张三" in d）
#   查值：值 in 字典.values()（95 in d.values()）
#   注意：in 字典 默认查的是键，不是值
# 【补充】根据值找键怎么操作？
#   推导式：{name for name, score in d.items() if score == 90} 或返回列表
#   值不重复时反转字典：{v: k for k, v in d.items()} 然后 d[90]
#   值可能重复时用推导式更安全（反转会丢失重复值）

# 【记忆口诀】
# 列表像"购物车"（能增删改）
# 元组像"合同"（定好不改）
# 字典像"通讯录"（按名字查）
# 集合像"记名册"（不重复）


