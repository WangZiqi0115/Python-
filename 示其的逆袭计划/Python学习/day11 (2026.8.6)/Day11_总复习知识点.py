# 六、推导式 / 生成器 / lambda（Day 10）
# ============================================================
# 列表推导式：[表达式 for 变量 in 可迭代 if 条件]
# 字典推导式：{键表达式: 值表达式 for ...}
# 集合推导式：{表达式 for ...}
# 生成器表达式：(表达式 for ...) → 懒计算、省内存、只能用一次
# lambda：一行匿名函数，常用于 key= / map / filter
#
# 【重点】if 在最后 = 过滤；if/else 在最前 = 选值
#   [x for x in ... if 条件]        → 过滤
#   ["大" if x > 5 else "小" for x]  → 选值
#
# 【重点】嵌套推导式：外层 for 在前，内层 for 在后
#   [num for row in matrix for num in row]


