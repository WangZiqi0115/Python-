# 七、十天的"错题本"（重点回顾）
# ============================================================
# 1. 忘加括号：word.lower() 不是 word.lower
# 2. append/sort/赋值返回 None：先操作再 return
# 3. 遍历解包变量名对应：for name, score in d.items()
# 4. 修改字典：d[key]=v，不要整体重新赋值
# 5. 索引从 0 数：第 n 个元素是 parts[n-1]
# 6. 文件对象一次遍历；读多次先存列表
# 7. f.write() 只接一个字符串；多行加 \n
# 8. 排序想清楚 reverse=True 升降序
# 9. lambda 直接赋值不加 []
# 10. round(x, n) 带保留位数参数


