# ============================================================
# 一、四大容器总览（Day 1-4）
# ============================================================
# 列表 []    ：有序、可变、可重复 → 动态数据
# 元组 ()    ：有序、不可变、可重复 → 固定数据
# 字典 {}    ：键值对、可变、key 不重复 → 按名字查找
# 集合 {}    ：无序、可变、元素不重复 → 去重/集合运算
#
# 创建：
#   list / tuple / dict / set
# 转换：
#   list(t) set(d) dict(zip(keys, values))
# 常用操作：
#   增删改查、遍历、推导式、sorted、len、in
# 【补充】怎么查字典里有没有某个键或值？
#   查键：键 in 字典（"张三" in d）
#   查值：值 in 字典.values()（95 in d.values()）
#   注意：in 字典 默认查的是键，不是值

# 【记忆口诀】
# 列表像"购物车"（能增删改）
# 元组像"合同"（定好不改）
# 字典像"通讯录"（按名字查）
# 集合像"记名册"（不重复）


# ============================================================
# 二、字符串方法（Day 5）
# ============================================================
# 大小写：lower / upper / title
# 查找：find（-1 不报错）/ index（找不到报错）
# 判断：startswith / endswith / isdigit / isalpha
# 切割拼接：split / join
# 清洗：strip / lstrip / rstrip / replace
# 【补充】四个清洗方法分别干嘛？
#   strip()   去掉首尾空白："  hi  " → "hi"
#   lstrip()  只去左边空白："  hi  " → "hi  "
#   rstrip()  只去右边空白："  hi  " → "  hi"
#   replace(旧, 新) 全文替换内容："hi hi".replace("hi","bye") → "bye bye"
# 格式化：f"{name}：{score}分" / f"{x:.2f}" / f"{x:>10}"
#
# 【重点】字符串不可变：方法返回新字符串，原字符串不变
#   s = "hello"; s.upper() → s 还是 "hello"（要重新赋值）


# ============================================================
# 三、函数（Day 7）
# ============================================================
# def 函数名(参数): ... return 结果
# 参数：位置参数 / 关键字参数 / 默认参数（默认值陷阱用 None 修复）
# 返回值：return 立刻结束函数；没有 return 返回 None
# 作用域：函数内局部变量不影响全局
# 函数作为参数：sorted(key=len)、max(d, key=d.get)、lambda
# 返回多个值：return a, b → 元组解包接收
#
# 【重点】区分"有没有返回值"：
#   只做事不交差（append/sort/remove/赋值）→ None
#   做事还交差（pop/copy/sorted/get/max）→ 返回值


