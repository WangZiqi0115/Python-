# 四、文件操作与异常（Day 8）
# ============================================================
# with open(文件, "r"/"w"/"a", encoding="utf-8") as f:
#   f.read()      → 全部内容（字符串）
#   f.readlines() → 全部内容（列表）
#   for line in f → 逐行（字符串）
#   f.write()     → 写入（不会自动换行，要加 \n）
#
# 异常处理：
# try:
#     可能出错的代码
# except 具体异常类型:
#     出错后执行
# else:   没出错执行
# finally: 无论如何执行
#
# 【重点】文件对象只能用一次遍历；中文读写加 encoding="utf-8"
# 【补充】为什么中文读写要加 encoding="utf-8"？
#   编码规则 = 文字的"翻译字典"（UTF-8 / GBK 是两种字典）
#   同一个"张"字，UTF-8 存 E5 BC A0，GBK 存 D5 C5
#   写文件用 UTF-8、读文件用 GBK → 用错字典 → 乱码/报错
#   Windows 默认用 GBK，所以读 UTF-8 写的中文文件必须显式指定 utf-8
#   UTF-8 是国际通用标准（能存所有语言），跨平台传文件最稳


