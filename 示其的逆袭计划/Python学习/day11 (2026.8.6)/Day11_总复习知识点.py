# 三、函数（Day 7）
# ============================================================
# def 函数名(参数): ... return 结果
# 参数：位置参数 / 关键字参数 / 默认参数（默认值陷阱用 None 修复）
# 【补充】位置参数和关键字参数的区别：
#   位置参数：按顺序传 info("示其", 18, "重庆")，顺序不能乱
#   关键字参数：按名字传 info(city="重庆", age=18, name="示其")，顺序可打乱
#   混合用：位置参数在前，关键字参数在后 info("示其", city="重庆")
#   默认参数：不传就用默认值 greet("示其") → greeting="你好"
# 【补充】max(字典, key=lambda x: x[1]) 的坑：
#   遍历字典时 x 是"键"（人名），x[1] 取的是名字第2个字，不是分数！
#   正确写法 1：max(scores, key=scores.get)
#   正确写法 2：max(scores.items(), key=lambda x: x[1])[0]
#   先想清楚 x 是什么类型，再决定怎么取
# 【补充】sorted 默认从低到高（升序）：
#   记忆：sorted 以 s 开头，small 也以 s 开头 → 从小到大
#   要降序必须显式加 reverse=True
# 返回值：return 立刻结束函数；没有 return 返回 None
# 作用域：函数内局部变量不影响全局
# 函数作为参数：sorted(key=len)、max(d, key=d.get)、lambda
# 返回多个值：return a, b → 元组解包接收
#
# 【重点】区分"有没有返回值"：
#   只做事不交差（append/sort/remove/赋值）→ None
#   做事还交差（pop/copy/sorted/get/max）→ 返回值


