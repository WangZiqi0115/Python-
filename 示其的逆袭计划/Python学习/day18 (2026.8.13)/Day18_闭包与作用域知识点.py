# ------------------------------------------------------------
# 例题 1：固定倍数工厂
# 题目：写 make_multiplier(n)，返回一个函数 f(x) = x * n
# 思路：内层函数读取外层 n，返回内层函数，形成闭包
# ------------------------------------------------------------
def make_multiplier(n):
    def multiplier(x):
        return x * n
    return multiplier

times_3 = make_multiplier(3)
print(times_3(4))               # 12
print(times_3(10))               # 30

# 关键点：make_multiplier 结束后，multiplier 仍然记得 n


# ------------------------------------------------------------
# 例题 2：nonlocal 计数器
# 题目：写 make_counter()，每次调用返回 1、2、3...
# 思路：count 放外层，内层用 nonlocal 修改它
# ------------------------------------------------------------
def make_counter_example():
    count = 0
    def counter():
        nonlocal count
        count += 1
        return count
    return counter

my_counter = make_counter_example()
print(my_counter())             # 1
print(my_counter())             # 2
print(my_counter())             # 3

# 关键点：不写 nonlocal，count += 1 会报错


# ------------------------------------------------------------
# 例题 3：循环闭包陷阱与修复
# 题目：返回 [0, 2, 4]，但直接写 lambda 会得到 [4, 4, 4]
# 思路：用默认参数 i=i 把当前值焊进每个 lambda
# ------------------------------------------------------------
def create_funcs():
    funcs = []
    for i in range(3):
        funcs.append(lambda i=i: i * 2)
    return funcs

print([f() for f in create_funcs()])    # [0, 2, 4]

# 关键点：i=i 等于"现在就把 i 的值存进默认参数"


# ------------------------------------------------------------
# 例题 4：闭包实现累加器
# 题目：acc(1) -> 1；acc(2) -> 3；acc(3) -> 6
# 思路：total 放外层，nonlocal 修改，每次加完返回 
# ------------------------------------------------------------
def make_accumulator_example():
    total = 0
    def add(value):
        nonlocal total
        total += value
        return total
    return add

acc = make_accumulator_example()
print(acc(1))                   # 1
print(acc(2))                   # 3
print(acc(3))                   # 6

# 关键点：闭包让函数"记住"了 total，不用全局变量
