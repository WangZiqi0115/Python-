# ============================================================
# 一、复习：函数本身也是"值"
# ============================================================
# Day 7 学过：函数名不加括号，就是把这个函数当作值传来传去
def add_one(x):
    return x + 1

func = add_one          # func 指向同一个函数
print(func(5))          # 6

# 函数还可以作为返回值，这就是闭包的起点


# ============================================================
# 二、作用域回顾：局部 vs 全局
# ============================================================
# 函数内部定义的变量是局部的，外面看不到
# 模块顶层定义的变量是全局的，函数内部可以读取

global_x = 10            # 全局变量

def show():
    local_y = 20         # 局部变量
    return global_x + local_y

print(show())            # 30

# 在函数内部给变量赋值，会创建新的局部变量
# 想修改全局变量要用 global（Day 7 学过，了解即可）


# ============================================================
# 三、嵌套函数：函数里面再定义函数
# ============================================================
def outer():
    def inner():
        return "我是内层函数"
    return inner()

print(outer())           # 我是内层函数

# 内层函数能读取外层函数的变量：
def outer2(name):
    def inner2():
        return f"你好，{name}"
    return inner2()

print(outer2("张三"))    # 你好，张三

# 注意：inner 只在 outer 内部存在，外面不能直接调用


# ============================================================
# 四、LEGB 查找顺序（重点）
# ============================================================
# Python 找变量时按这个顺序一层层找，找到就停：
#   L = Local          当前函数里的局部变量
#   E = Enclosing      外层函数里的变量
#   G = Global         模块顶层的全局变量
#   B = Built-in       Python 内置名字（len、print 等）

x = "global"             # Global

def outer3():
    x = "enclosing"      # Enclosing
    def inner3():
        x = "local"      # Local
        return x
    return inner3()

print(outer3())          # local，最近的一层先赢

# 如果把内层那行去掉，就会返回 "enclosing"；再往外是 "global"


# ============================================================
# 五、闭包是什么（重点）
# ============================================================
# 闭包 = 内层函数 + 它记住的外层变量
# 即使外层函数已经执行结束，内层函数仍然记得外层变量

def make_adder(n):
    def adder(x):
        return x + n     # n 是外层函数的变量，被内层记住了
    return adder         # 把内层函数交出去

add_5 = make_adder(5)    # 外层函数结束，但 adder 记得 n=5
print(add_5(3))          # 8
print(add_5(100))        # 105

# 类比：adder 是一台"加 n 的机器"，n 在出厂时就焊死了


# ============================================================
# 六、nonlocal：修改外层函数的变量（重点）
# ============================================================
# 内层函数只能"读"外层变量；想"修改"它，要声明 nonlocal

def make_counter():
    count = 0            # 外层变量
    def counter():
        nonlocal count   # 声明：我要修改外层这个 count
        count += 1
        return count
    return counter

c = make_counter()
print(c())               # 1
print(c())               # 2
print(c())               # 3

# 如果不写 nonlocal，count += 1 会被当成"创建新的局部变量"
# 第一次调用就报 UnboundLocalError


# ============================================================
# 七、global vs nonlocal
# ============================================================
# global    = 修改"模块顶层"的全局变量
# nonlocal  = 修改"最近的外层函数"里的变量

score = 0                # 全局变量

def add_global():
    global score
    score += 1

add_global()
add_global()
print(score)             # 2

# nonlocal 不能直接出现在模块顶层，只能在嵌套函数里用


# ============================================================
# 八、闭包陷阱：循环里的 lambda（重点）
# ============================================================
# 你以为每个 lambda 记住的是自己的 i，其实记住的是同一个 i 的最终值
funcs = []
for i in range(3):
    funcs.append(lambda: i * 2)

print([f() for f in funcs])     # [4, 4, 4]  不是 [0, 2, 4]！

# 【补充】f 后面为什么要加括号？
#   funcs 里装的不是数字，而是"函数本身"
#   for f in funcs：f 是一个 lambda 函数对象（地址）
#   f()：调用这个函数，执行 lambda 才得到真正的数字
#   直接写 funcs 只会打印函数的地址列表
#   类比：f 是菜谱，f() 是照着菜谱做出来的菜
#   记忆：函数名不加括号 = 把函数当值；加括号 = 让函数干活

# 【补充】为什么结果是 [4, 4, 4] 而不是 [0, 2, 4]？
#   关键：lambda 里的 i 不是"创建那一刻的 i 值"，而是"对变量 i 的引用"
#   循环过程：
#     i = 0 → 放入第 1 个 lambda（它记住的是"读变量 i"）
#     i = 1 → 放入第 2 个 lambda
#     i = 2 → 放入第 3 个 lambda
#   循环结束后，变量 i 停在最终值 2
#   最后调用 f() 时，三个 lambda 读的是同一个 i，看到的都是 2
#   所以都是 2 * 2 = 4
#   类比：lambda 是纸条"i × 2"，i 是黑板上的值；循环结束黑板上写着 2
#   修复：lambda i=i: i * 2 在创建时把当前 i 复印进默认参数，不再看黑板

# 【补充】为什么三个 lambda 读的是同一个 i？
#   1. 变量是"名字"不是"盒子"：i 从头到尾是同一个名字
#   2. for i in range(3) 只是让这个名字依次指向 0、1、2，最后停在 2
#   3. lambda 不会在定义时执行，它记住的是"要读 i 这个名字"
#   4. 三个 lambda 读的是同一个名字 i，就像三张纸条都写"看黑板 i"
#   5. 循环结束后黑板上是 2，所以三个都算出 4
#   修复原理：lambda i=i 把"当时的数字"复印进自己的默认参数
#     纸条变成"看我自己默认参数里的数字"，不再看黑板

# 修复 1：用默认参数把 i 的值"当场焊死"
funcs_fixed = []
for i in range(3):
    funcs_fixed.append(lambda i=i: i * 2)

print([f() for f in funcs_fixed])  # [0, 2, 4]

# 修复 2：用工厂函数，每次调用都生成独立闭包
def make_mul(i):
    return lambda: i * 2

funcs_fixed2 = [make_mul(i) for i in range(3)]
print([f() for f in funcs_fixed2])  # [0, 2, 4]


